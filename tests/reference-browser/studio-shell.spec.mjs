import { test, expect } from '@playwright/test'
import { openStudioTool } from '../studio-helpers.mjs'
import { mkdir } from 'node:fs/promises'

test('selected site opens an immersive studio without modelled buildings; tools preserve drafts', async ({ page, request }, testInfo) => {
  const login = await request.post('http://127.0.0.1:8001/auth/v1/token', { data: { email: 'fixture@example.invalid', password: 'fixture-only' } })
  const headers = { Authorization: `Bearer ${(await login.json()).access_token}` }
  const org = (await (await request.get('/api/v1/session', { headers })).json()).organisations[0].id
  const created = await request.post(`/api/v1/organisations/${org}/projects`, { headers, data: { name: 'Immersive studio review', purpose: 'contractor_proposal', stakeholder: 'Test only', site: { bounds: [101.681, 3.131, 101.683, 3.133] } } })
  expect(created.status()).toBe(201)
  const project = await created.json()
  await mkdir('artifacts', { recursive: true })
  await page.goto('/')
  await page.getByLabel('Email address').waitFor()
  await page.screenshot({ path: 'artifacts/theme-login.png', animations: 'disabled' })
  await page.getByLabel('Email address').fill('fixture@example.invalid')
  await page.getByLabel('Password', { exact: true }).fill('fixture-only')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  // Sign-in lands on Home; the workspace switcher belongs to the Design Studio project list.
  await page.getByRole('button', { name: 'Open Design Studio', exact: true }).click()
  const organisation = page.getByRole('combobox', { name: 'Organisation', exact: true })
  await page.getByText('Change workspace', { exact: true }).click()
  await expect(organisation).toBeVisible()
  if (await organisation.inputValue() !== org) await organisation.selectOption(org)
  await page.getByText('Change workspace', { exact: true }).click()
  await expect(organisation).toBeHidden()
  await expect(page.getByRole('button', { name: /Immersive studio review/ })).toBeVisible()
  await expect(page.getByLabel('Sort projects', { exact: true })).toBeHidden()
  await page.getByText(/^More filters and options/).click()
  await expect(page.getByLabel('Sort projects', { exact: true })).toBeVisible()
  await page.getByRole('combobox', { name: 'Status', exact: true }).selectOption('estimate')
  // Other specs in the same run may leave Estimate-stage projects; this project must be filtered out.
  await expect(page.getByRole('button', { name: /Immersive studio review/ })).toHaveCount(0)
  await page.getByRole('combobox', { name: 'Status', exact: true }).selectOption('')
  await expect(page.getByRole('button', { name: /Immersive studio review/ })).toBeVisible()
  await page.getByText(/^More filters and options/).click()
  await page.getByLabel('Search projects or stakeholders').fill('no-such-project-unique')
  await page.getByRole('button', { name: 'Search projects', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'No matching projects' })).toBeVisible()
  await page.getByRole('button', { name: 'Clear filters', exact: true }).click()
  await expect(page.getByRole('button', { name: /Immersive studio review/ })).toBeVisible()
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: 'artifacts/theme-dashboard.png', animations: 'disabled' })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: 'artifacts/theme-dashboard-phone.png', animations: 'disabled' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.getByRole('button', { name: /Immersive studio review/ }).click()
  const map = page.getByRole('region', { name: 'Geometry drawing canvas', exact: true })
  await expect(map.getByRole('button', { name: '3D buildings', exact: true })).toBeEnabled({ timeout: 45000 })
  await expect(map).toHaveAttribute('data-known-buildings', '0')
  await expect(map).toHaveAttribute('data-view-mode', '3d')
  if (testInfo.config.configFile.endsWith('playwright.studio.config.mjs')) await expect(map).not.toHaveAttribute('data-context-buildings', '0', { timeout: 45000 })
  // Building coverage controls are hidden in the simple Layout view; the Layout panel's precision tools show them.
  await openStudioTool(page, 'Layout')
  const precisionTools = page.getByRole('button', { name: 'Precision tools', exact: true })
  if (await precisionTools.isVisible()) await precisionTools.click()
  await map.getByText('Building coverage & sources', { exact: true }).click()
  const ring = [[101.681,3.131],[101.682,3.131],[101.682,3.132],[101.681,3.131]]
  await map.getByLabel('Building context GeoJSON').setInputFiles({name:'context.geojson',mimeType:'application/geo+json',buffer:Buffer.from(JSON.stringify({type:'FeatureCollection',features:[{type:'Feature',properties:{height:12},geometry:{type:'Polygon',coordinates:[ring]}},{type:'Feature',properties:{},geometry:{type:'Polygon',coordinates:[ring]}}]}))})
  await expect(map.getByRole('status').filter({hasText:'2 local footprints'})).toContainText('1 unknown heights stay flat')
  await map.getByRole('button',{name:'Use provider buildings',exact:true}).click()
  await expect(map.getByText(/2 local footprints/)).toHaveCount(0)
  await map.getByText('Building coverage & sources', { exact: true }).click()
  const dock = page.getByRole('navigation', { name: 'Studio tools' })
  await openStudioTool(page, 'Layout')
  await page.getByRole('button', { name: 'Start building on this site' }).click()
  await page.getByLabel('Geometry name', { exact: true }).fill('Unapplied boundary name')
  await openStudioTool(page, 'Terrain')
  await expect(page.getByLabel('Geometry name', { exact: true })).toBeHidden()
  await openStudioTool(page, 'Layout')
  await expect(page.getByLabel('Geometry name', { exact: true })).toHaveValue('Unapplied boundary name')
  await dock.getByRole('button', { name: 'Explore', exact: true }).click()
  await expect(page.getByRole('complementary', { name: 'Studio working panel' })).toBeHidden()
  await mkdir('artifacts', { recursive: true })
  await page.screenshot({ path: 'artifacts/studio-desktop.png', animations: 'disabled' })
  await page.setViewportSize({ width: 390, height: 844 })
  await openStudioTool(page, 'Layout')
  await page.screenshot({ path: 'artifacts/studio-phone.png', animations: 'disabled' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.emulateMedia({ reducedMotion: 'reduce' })
  const layoutTool = dock.getByRole('button', { name: 'Layout', exact: true })
  await expect(layoutTool).toHaveAttribute('aria-expanded', 'true')
  await layoutTool.hover()
  await expect(layoutTool).toHaveCSS('transform', 'none')
  await expect(layoutTool).toHaveCSS('transition-duration', '0s')
  await layoutTool.focus()
  await page.keyboard.press('Enter')
  await expect(page.getByLabel('Geometry name', { exact: true })).toHaveValue('Unapplied boundary name')
  // Visual exploration and an unsaved draft never create server quantities or objects.
  const saved = await (await request.get(`/api/v1/organisations/${org}/projects/${project.id}/workspace`, { headers })).json()
  expect(saved.data).toBeNull()
  page.once('dialog', dialog => dialog.dismiss())
  await page.getByRole('button', { name: 'Project details', exact: true }).click()
  await expect(dock).toBeVisible()
})
