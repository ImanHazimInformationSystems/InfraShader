import { test, expect } from '@playwright/test'
import { mkdir } from 'node:fs/promises'

test('explorer tutorial guides without changing coordinates and supports keyboard/mobile/reduced motion', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Open Browser Demo' }).click()
  await page.getByRole('button', { name: 'New project', exact: true }).click()
  const tips = page.getByRole('button', { name: 'Tips / tutorial', exact: true })
  const coords = ['West longitude', 'South latitude', 'East longitude', 'North latitude']
  const before = await Promise.all(coords.map(label => page.getByLabel(label, { exact: true }).inputValue()))
  await tips.click()
  const guide = page.getByRole('dialog')
  await expect(guide).toBeVisible()
  await expect(guide.getByRole('heading', { name: 'Find your place' })).toBeVisible()
  await expect(guide.getByRole('button', { name: 'Back', exact: true })).toBeDisabled()
  await expect(guide.getByRole('button', { name: 'Close tutorial' })).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(guide.getByRole('button', { name: 'Next', exact: true })).toBeFocused()
  await mkdir('artifacts', { recursive: true })
  await page.screenshot({ path: 'artifacts/explore-tutorial-desktop.png', animations: 'disabled' })
  await page.keyboard.press('Escape')
  await expect(guide).not.toBeVisible()
  await expect(tips).toBeFocused()
  await tips.click()
  await guide.getByRole('button', { name: 'Next', exact: true }).click()
  await expect(guide.getByRole('heading', { name: 'Mark your site' })).toBeVisible()
  await guide.getByRole('button', { name: 'Back', exact: true }).click()
  await expect(guide.getByRole('heading', { name: 'Find your place' })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await guide.getByRole('button', { name: 'Next', exact: true }).click()
  await page.screenshot({ path: 'artifacts/explore-tutorial-phone.png', animations: 'disabled' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await guide.getByRole('button', { name: 'Next', exact: true }).click()
  await expect(guide.locator('.tutorial-step')).toHaveCSS('animation-name', 'none')
  await expect(guide.getByRole('heading', { name: 'Check the selected area' })).toBeVisible()
  await guide.getByRole('button', { name: 'Next', exact: true }).click()
  await expect(guide.getByRole('heading', { name: 'Start your project' })).toBeVisible()
  await guide.getByRole('button', { name: 'Start exploring', exact: true }).click()
  await expect(guide).not.toBeVisible()
  expect(await Promise.all(coords.map(label => page.getByLabel(label, { exact: true }).inputValue()))).toEqual(before)
  await tips.click()
  await expect(guide.getByRole('heading', { name: 'Find your place' })).toBeVisible()
  await guide.getByRole('button', { name: 'Skip guide' }).click()
  await expect(tips).toBeFocused()
  await page.screenshot({ path: 'artifacts/explore-tutorial-trigger-phone.png', animations: 'disabled' })
  await page.getByRole('button', { name: 'Continue with this site', exact: true }).click()
  await expect(page.getByLabel('Project name')).toBeVisible()
})

