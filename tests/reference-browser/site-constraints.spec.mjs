import { openDetailedWorkspace } from '../studio-helpers.mjs'
import {test,expect} from '@playwright/test'
import {mkdir,readFile} from 'node:fs/promises'
import {randomUUID} from 'node:crypto'

test('L03 consent, verification queue, evidence links and revision persistence',async({page,request})=>{
  test.setTimeout(120000)
  const login=await request.post('http://127.0.0.1:8001/auth/v1/token',{data:{email:'fixture@example.invalid',password:'fixture-only'}})
  expect(login.ok()).toBeTruthy()
  const headers={Authorization:`Bearer ${(await login.json()).access_token}`}
  const org=(await (await request.get('/api/v1/session',{headers})).json()).organisations[0].id
  const result=await request.post(`/api/v1/organisations/${org}/projects`,{headers,data:{name:'L03 site evidence',purpose:'contractor_proposal',stakeholder:'Test only',site:{bounds:[101.681,3.131,101.683,3.133]}}})
  expect(result.status()).toBe(201)
  const project=await result.json(),endpoint=`/api/v1/organisations/${org}/projects/${project.id}`
  const polygon={type:'Polygon',coordinates:[[[101.681,3.131],[101.683,3.131],[101.683,3.133],[101.681,3.133],[101.681,3.131]]]}
  const target={id:randomUUID(),name:'Traced target',geometry:polygon,provenance:'estimated',source_note:'Synthetic control plan'}
  const data={expected_revision:0,boundary:polygon,boundary_provenance:'estimated',boundary_source:'Synthetic',targets:[target],scenarios:{baseline:{name:'Baseline',items:[]},option_a:{name:'A',items:[{id:randomUUID(),name:'Concept bench',kind:'bench',geometry:{type:'Point',coordinates:[101.6815,3.1325]},provenance:'estimated',source_note:'Synthetic object'}]},option_b:{name:'B',items:[]}}}
  expect((await request.post(`${endpoint}/workspace`,{headers,data})).ok()).toBeTruthy()
  await page.goto('/')
  await page.getByLabel('Email address').fill('fixture@example.invalid')
  await page.getByLabel('Password',{exact:true}).fill('fixture-only')
  await page.getByRole('button',{name:'Sign in',exact:true}).click()
  const organisation=page.getByRole('combobox',{name:'Active organisation',exact:true})
  await expect(organisation).toBeVisible()
  if(await organisation.inputValue()!==org) await organisation.selectOption(org)
  await page.getByRole('button',{name:/L03 site evidence/}).click()
  await openDetailedWorkspace(page)
  await page.getByRole('group',{name:'Scenario selection'}).getByRole('button',{name:'A',exact:true}).click()
  const register=page.getByRole('region',{name:'Survey evidence and constraints',exact:true})
  await register.getByLabel('Constraint title',{exact:true}).fill('Utility needs inspection')
  await register.getByRole('combobox',{name:'Constraint category',exact:true}).selectOption('utility')
  await register.getByLabel('Observation or constraint details',{exact:true}).fill('Synthetic utility observation; never excavation advice')
  await register.getByLabel('Source document, person or measurement reference',{exact:true}).fill('Synthetic plan note A')
  await register.getByLabel('Uncertainty and limits',{exact:true}).fill('Depth and alignment unknown')
  await register.getByRole('combobox',{name:'Location geometry',exact:true}).selectOption('Point')
  await register.getByLabel('Constraint longitude, latitude coordinates',{exact:true}).fill('101.682, 3.132')
  await register.getByRole('button',{name:'Apply constraint to draft',exact:true}).click()
  await expect(register.getByRole('alert')).toContainText('permission')
  await register.getByRole('checkbox',{name:'Permission to record this location is confirmed',exact:true}).check()
  await register.getByLabel('Location permission basis',{exact:true}).fill('Synthetic site owner permission')
  await register.getByRole('combobox',{name:'Verification status',exact:true}).selectOption('site_check')
  await register.getByLabel('Responsible person',{exact:true}).fill('Fixture survey lead')
  await register.getByLabel('Site check due date',{exact:true}).fill('2026-11-10')
  await register.getByRole('checkbox',{name:'Critical fact requiring review',exact:true}).check()
  await register.getByLabel('Design response or proposed action',{exact:true}).fill('Keep proposal clear until inspected')
  await register.getByRole('listbox',{name:'Linked design geometry',exact:true}).selectOption(target.id)
  const upload=await request.post(`${endpoint}/evidence`,{headers,multipart:{description:'L03 private photo',source_note:'Synthetic private evidence',rights_confirmed:'true',photo:{name:'fixture.png',mimeType:'image/png',buffer:await readFile('tests/fixtures/l05-green.png')}}})
  expect(upload.ok()).toBeTruthy()
  const photo=await upload.json()
  await register.getByRole('button',{name:'Refresh evidence list',exact:true}).click()
  await register.getByRole('checkbox',{name:'L03 private photo',exact:true}).check()
  await register.getByRole('button',{name:'Apply constraint to draft',exact:true}).click()
  await expect(register.getByText('Constraint applied to the draft.',{exact:false})).toBeVisible()
  await page.getByRole('button',{name:'Validate & save workspace',exact:true}).click()
  await expect(page.getByText('Workspace revision 2 saved.',{exact:false})).toBeVisible()
  let saved=(await (await request.get(`${endpoint}/workspace`,{headers})).json()).data
  expect(saved.constraints[0].evidence_ids).toEqual([photo.id])
  expect(saved.constraints[0].related_ids).toEqual([target.id])
  expect(saved.constraints[0].status).toBe('site_check')
  await page.getByRole('checkbox',{name:'Show constraint layer',exact:true}).uncheck()
  await expect(page.getByRole('button',{name:'Validate & save workspace',exact:true})).toBeDisabled()
  await page.reload();await openDetailedWorkspace(page)
  await register.getByRole('checkbox',{name:'Show verification queue only',exact:true}).check()
  await register.getByRole('button',{name:'Review Utility needs inspection',exact:true}).click()
  await expect(register.getByLabel('Responsible person',{exact:true})).toHaveValue('Fixture survey lead')
  await register.getByRole('combobox',{name:'Verification status',exact:true}).selectOption('resolved')
  await register.getByLabel('Verified by',{exact:true}).fill('Fixture inspector')
  await register.getByLabel('Verification date',{exact:true}).fill('2026-11-01')
  await register.getByLabel('Supplied verification reference',{exact:true}).fill('Synthetic supplied inspection A1')
  await register.getByLabel('Resolution and result',{exact:true}).fill('Revised the proposed layout; no excavation approval')
  await register.getByRole('button',{name:'Apply constraint to draft',exact:true}).click()
  await expect(register.getByRole('alert')).toContainText('cannot claim verification')
  await register.getByRole('combobox',{name:'Constraint source type',exact:true}).selectOption('supplied')
  await register.getByRole('button',{name:'Apply constraint to draft',exact:true}).click()
  await expect(register.getByRole('button',{name:'Review Utility needs inspection',exact:true})).toHaveCount(0)
  await page.getByRole('button',{name:'Validate & save workspace',exact:true}).click()
  await expect(page.getByText('Workspace revision 3 saved.',{exact:false})).toBeVisible()
  saved=(await (await request.get(`${endpoint}/workspace`,{headers})).json()).data
  expect(saved.constraints[0].status).toBe('resolved')
  await register.getByRole('checkbox',{name:'Show verification queue only',exact:true}).uncheck()
  await mkdir('artifacts',{recursive:true})
  await register.screenshot({path:'artifacts/l03-register-desktop.png'})
  await page.setViewportSize({width:390,height:844})
  await register.screenshot({path:'artifacts/l03-register-phone.png'})
})
