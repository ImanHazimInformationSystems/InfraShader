import { test, expect } from '@playwright/test'
import { mkdir } from 'node:fs/promises'
import { randomUUID } from 'node:crypto'
import { openDetailedWorkspace, openStudioTool } from '../studio-helpers.mjs'

test('terrain town-builder strokes, water, undo, manual costs and stale review survive save', async ({ page, request }) => {
  test.setTimeout(150000)
  page.setDefaultTimeout(15000)
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  const login = await (await request.post('http://127.0.0.1:8001/auth/v1/token', { data: { email: 'fixture@example.invalid', password: 'fixture-only' } })).json()
  const headers = { Authorization: `Bearer ${login.access_token}` }
  const org = (await (await request.get('/api/v1/session', { headers })).json()).organisations[0].id
  const project = await (await request.post(`/api/v1/organisations/${org}/projects`, { headers, data: { name: 'Terrain brush playground', purpose: 'contractor_proposal', stakeholder: 'Synthetic fixture', site: { bounds: [101.681, 3.131, 101.683, 3.133] } } })).json()
  const endpoint = `/api/v1/organisations/${org}/projects/${project.id}`
  const boundary = { type: 'Polygon', coordinates: [[[101.681, 3.131], [101.683, 3.131], [101.683, 3.133], [101.681, 3.133], [101.681, 3.131]]] }
  const initial = { expected_revision: 0, boundary, boundary_source: 'Synthetic', boundary_provenance: 'estimated', targets: [], scenarios: { baseline: { name: 'Baseline', items: [] }, option_a: { name: 'A', items: [] }, option_b: { name: 'B', items: [] } } }
  expect((await request.post(`${endpoint}/workspace`, { headers, data: initial })).ok()).toBeTruthy()
  const rate = await (await request.post(`/api/v1/organisations/${org}/rates`, { headers, data: { code: `TERRAIN-${randomUUID().slice(0, 8)}`, description: 'Synthetic crew hourly allowance', unit: 'h', basis: 'cost', amount: '20', effective_date: '2026-01-01', valid_until: '2099-12-31', source_note: 'Synthetic test only, not a real supplier rate', includes: [] } })).json()
  await page.goto('/')
  await page.getByLabel('Email address').fill('fixture@example.invalid'); await page.getByLabel('Password', { exact: true }).fill('fixture-only')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  const organisation = page.getByLabel('Active organisation', { exact: true }); await expect(organisation).toBeVisible()
  if (await organisation.inputValue() !== org) await organisation.selectOption(org)
  await page.getByRole('button', { name: /Terrain brush playground/ }).click()
  await openDetailedWorkspace(page); await page.getByLabel('Embed design on map', { exact: true }).check()
  await page.getByRole('button', { name: 'Map view', exact: true }).click()
  const tools = page.getByRole('navigation', { name: 'Studio tools' })
  await openStudioTool(page, 'Terrain')
  const panel = page.getByRole('region', { name: 'Terrain builder', exact: true })
  await expect(panel.getByRole('group', { name: 'Terrain brushes' })).toBeVisible()
  await expect(panel.getByRole('button', { name: 'Raise hills', exact: true })).toBeDisabled()
  await expect(panel.getByText(/Brushes activate after you describe and confirm/)).toBeVisible()
  await panel.getByLabel('Surface source / assumption', { exact: true }).fill('Synthetic flat start for UI verification; no survey')
  await panel.getByLabel('I confirm this flat starting assumption.', { exact: true }).check()
  await panel.getByRole('button', { name: 'Prepare terrain', exact: true }).click()
  await expect(panel.getByRole('group', { name: 'Terrain brushes' })).toBeVisible()
  await expect(panel.getByRole('button', { name: 'Raise hills', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(panel.getByRole('button', { name: 'Raise hills', exact: true })).toBeInViewport()
  await expect(panel.getByRole('group', { name: 'Brush shape', exact: true })).toBeVisible()
  await expect(panel.getByLabel('Terrain brush size', { exact: true })).toBeEnabled()
  const canvas = page.getByRole('region', { name: 'Geometry drawing canvas', exact: true }).locator('.mapboxgl-canvas')
  await expect(canvas).toHaveAttribute('data-design-triangles', /\d+/)
  await panel.getByRole('button', { name: 'Raise hills', exact: true }).click()
  await page.waitForTimeout(500)
  const box = await canvas.boundingBox()
  let response = page.waitForResponse(r => r.url().endsWith('/object-preview') && r.request().method() === 'POST')
  await page.mouse.move(box.x + box.width * .45, box.y + box.height * .5)
  await page.mouse.down(); await page.waitForTimeout(500); await page.mouse.move(box.x + box.width * .47, box.y + box.height * .51, { steps: 8 }); await page.mouse.up()
  const raised = await (await response).json()
  expect(Math.max(...raised.scenarios.option_a.terrain.heights)).toBeGreaterThan(0)
  await expect(panel.getByRole('button', { name: 'Undo', exact: true })).toBeEnabled()
  await panel.getByRole('button', { name: 'Undo', exact: true }).click()
  await panel.getByRole('button', { name: 'Redo', exact: true }).click()
  await panel.getByRole('button', { name: 'Undo', exact: true }).click()
  let previews = 0; page.on('request', r => { if (r.url().endsWith('/object-preview') && r.method() === 'POST') previews++ })
  await page.mouse.move(box.x + box.width * .45, box.y + box.height * .5); await page.mouse.down(); await page.waitForTimeout(200); await page.keyboard.press('Escape'); await page.mouse.up()
  expect(previews).toBe(0)
  await panel.getByRole('button', { name: 'Dig', exact: true }).click()
  await panel.getByRole('button', { name: 'Square', exact: true }).click()
  await panel.getByLabel('Soft brush edges', { exact: true }).uncheck()
  await panel.getByLabel('Terrain brush speed', { exact: true }).press('End')
  await panel.getByLabel('Terrain target offset', { exact: true }).fill('-6')
  await panel.getByLabel('Terrain brush size', { exact: true }).press('Home')
  for (let i = 0; i < 45; i++) await panel.getByLabel('Terrain brush size', { exact: true }).press('ArrowRight')
  response = page.waitForResponse(r => r.url().endsWith('/object-preview') && r.request().method() === 'POST')
  await panel.getByRole('button', { name: 'Apply brush at site centre (1 second)', exact: true }).click()
  expect(Math.min(...(await (await response).json()).scenarios.option_a.terrain.heights)).toBe(-6)
  await panel.getByRole('button', { name: 'Pond water', exact: true }).click(); await panel.getByRole('button', { name: 'Circle', exact: true }).click()
  await panel.getByLabel('Terrain brush size', { exact: true }).press('Home')
  response = page.waitForResponse(r => r.url().endsWith('/object-preview') && r.request().method() === 'POST')
  await panel.getByRole('button', { name: 'Apply brush at site centre (1 second)', exact: true }).click()
  expect((await (await response).json()).scenarios.option_a.terrain.ponds[0].shape).toBe('circle')
  await page.getByRole('button', { name: 'Save design', exact: true }).click()
  await expect(page.getByText('Workspace revision 2 saved.', { exact: false })).toBeVisible()
  async function estimate(revision) { const result = await request.post(`${endpoint}/estimates`, { headers, data: { expected_revision: revision, request_key: randomUUID(), scenario: 'option_a', method: 'markup', percent: '0', wastage_percent: '0', charges: [] } }); expect(result.ok()).toBeTruthy(); return (await result.json()).payload }
  expect((await estimate(2)).missing_rates[0].item_id).toBe('terrain-scope')
  await panel.locator('summary').filter({ hasText: 'Site work & preliminary costs' }).click()
  await panel.getByLabel('Tools / resources needed', { exact: true }).fill('Two workers and shovels')
  await panel.getByLabel('Manual quantity', { exact: true }).fill('4')
  await panel.getByLabel('Quantity source and assumptions', { exact: true }).fill('Contractor supplied allowance; disposal and access preparation excluded')
  await panel.getByLabel('Compatible rate', { exact: true }).selectOption(rate.id)
  await panel.getByLabel('I reviewed these quantities, resources and assumptions for the current terrain.', { exact: true }).check()
  await panel.getByRole('button', { name: 'Add work record', exact: true }).click()
  await expect(panel.getByRole('button', { name: 'Review / edit', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Save design', exact: true }).click()
  await expect(page.getByText('Workspace revision 3 saved.', { exact: false })).toBeVisible()
  await openStudioTool(page, 'Terrain')
  await expect.poll(() => page.getByRole('complementary', { name: 'Studio working panel', exact: true }).evaluate(node => node.scrollTop)).toBe(0)
  expect((await estimate(3)).priced_subtotal).toBe('80.00')
  await expect(panel.getByText(/Saved cost MYR 80.00/)).toBeVisible()
  const saved = await (await request.get(`${endpoint}/workspace`, { headers })).json()
  expect(saved.data.scenarios.option_b.terrain).toBeNull()
  expect(saved.data.scenarios.option_a.items[0].quantity.calculated.unit).toBe('h')
  await mkdir('artifacts', { recursive: true })
  await panel.getByRole('button', { name: 'Explore', exact: true }).click()
  await page.screenshot({ path: 'artifacts/terrain-builder-desktop.png' })
  await panel.getByRole('button', { name: 'Remove water', exact: true }).click()
  await expect(panel.getByRole('button', { name: 'Remove water', exact: true })).not.toBeVisible()
  await page.getByRole('button', { name: 'Save design', exact: true }).click()
  await expect(page.getByText('Workspace revision 4 saved.', { exact: false })).toBeVisible()
  const stale = await estimate(4)
  expect(stale.complete).toBe(false); expect(stale.missing_rates[0].reason).toContain('Terrain changed')
  await page.reload(); await openDetailedWorkspace(page); await page.getByLabel('Embed design on map', { exact: true }).check()
  await page.getByRole('button', { name: 'Map view', exact: true }).click(); await openStudioTool(page, 'Terrain')
  await expect(panel.getByText('Terrain changed — review quantity and resources', { exact: true })).toBeVisible()
  page.once('dialog', dialog => dialog.accept())
  await panel.getByRole('button', { name: 'Reset surface', exact: true }).click()
  await panel.getByRole('button', { name: 'Undo', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await panel.getByRole('heading', { name: 'Build hills. Carve hollows.', exact: true }).scrollIntoViewIfNeeded()
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.screenshot({ path: 'artifacts/terrain-builder-phone.png' })
  expect(errors).toEqual([])
})
