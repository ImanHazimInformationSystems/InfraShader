import { test, expect } from '@playwright/test'
import { mkdir } from 'node:fs/promises'
import { openDetailedWorkspace, openStudioTool } from '../studio-helpers.mjs'

test('six grass brushes clip to the site, erase, undo, save and reload without billable items', async ({ page, request }) => {
  test.setTimeout(90000)
  page.setDefaultTimeout(15000)
  const identity = await (await request.post('http://127.0.0.1:8001/auth/v1/token', { data: { email: 'fixture@example.invalid', password: 'fixture-only' } })).json()
  const headers = { Authorization: `Bearer ${identity.access_token}` }
  const org = (await (await request.get('/api/v1/session', { headers })).json()).organisations[0].id
  const project = await (await request.post(`/api/v1/organisations/${org}/projects`, { headers, data: { name: 'Grass painting playground', purpose: 'contractor_proposal', stakeholder: 'Synthetic test', site: { bounds: [101.681, 3.131, 101.683, 3.133] } } })).json()
  const endpoint = `/api/v1/organisations/${org}/projects/${project.id}`
  const boundary = { type: 'Polygon', coordinates: [[[101.681, 3.131], [101.683, 3.131], [101.681, 3.133], [101.681, 3.131]]] }
  const initial = { expected_revision: 0, boundary, boundary_source: 'Synthetic triangle', boundary_provenance: 'estimated', targets: [], scenarios: { baseline: { name: 'Baseline', items: [] }, option_a: { name: 'A', items: [], ground_paint: [{ texture: 'lawn', radius_m: 100, points: [[101.6824, 3.1324]] }] }, option_b: { name: 'B', items: [] } } }
  expect((await request.post(`${endpoint}/workspace`, { headers, data: initial })).ok()).toBeTruthy()
  await page.goto('/')
  await page.getByLabel('Email address').fill('fixture@example.invalid')
  await page.getByLabel('Password', { exact: true }).fill('fixture-only')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  const organisation = page.getByLabel('Active organisation', { exact: true })
  await expect(organisation).toBeVisible()
  if (await organisation.inputValue() !== org) await organisation.selectOption(org)
  await page.getByRole('button', { name: /Grass painting playground/ }).click()
  await openDetailedWorkspace(page)
  await page.getByRole('button', { name: 'Map view', exact: true }).click()
  await openStudioTool(page, 'Layout')
  const town = page.getByRole('region', { name: 'Town builder layout', exact: true })
  await town.getByRole('button', { name: 'Ground', exact: true }).click()
  const panel = page.getByRole('region', { name: 'Ground paint', exact: true })
  for (const name of ['Fresh lawn', 'Meadow', 'Fine turf', 'Dry grass', 'Deep green', 'Wild grass']) await expect(panel.getByRole('button', { name, exact: true })).toBeVisible()
  const raster = page.locator('canvas[data-ground-paint="true"]')
  const pixels = () => raster.evaluate((canvas) => {
    const ctx = canvas.getContext('2d'), data = ctx.getImageData(0, 0, 1024, 1024).data
    let painted = 0
    for (let i = 3; i < data.length; i += 4) if (data[i]) painted++
    return { painted, outside: ctx.getImageData(950, 50, 1, 1).data[3], inside: ctx.getImageData(400, 700, 1, 1).data[3] }
  })
  await expect.poll(async () => (await pixels()).painted).toBeGreaterThan(0)
  expect((await pixels()).outside).toBe(0)
  const canvas = page.getByRole('region', { name: 'Geometry drawing canvas', exact: true }).locator('.mapboxgl-canvas')
  const box = await canvas.boundingBox()
  await panel.getByRole('button', { name: 'Deep green', exact: true }).click()
  const responsePromise = page.waitForResponse((response) => response.url().endsWith('/spatial-edit') && response.request().method() === 'POST')
  await page.mouse.move(box.x + box.width * 0.42, box.y + box.height * 0.53)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width * 0.49, box.y + box.height * 0.56, { steps: 8 })
  await page.mouse.up()
  expect((await responsePromise).ok()).toBeTruthy()
  await expect(panel.getByText('2/128 strokes', { exact: true })).toBeVisible()
  const beforeErase = (await pixels()).painted
  await panel.getByRole('button', { name: 'Eraser', exact: true }).click()
  await canvas.click({ position: { x: box.width * 0.45, y: box.height * 0.54 } })
  await expect(panel.getByText('3/128 strokes', { exact: true })).toBeVisible()
  await expect.poll(async () => (await pixels()).painted).toBeLessThan(beforeErase)
  await town.getByRole('button', { name: 'Undo layout change', exact: true }).click()
  await expect(panel.getByText('2/128 strokes', { exact: true })).toBeVisible()
  await town.getByRole('button', { name: 'Redo layout change', exact: true }).click()
  await expect(panel.getByText('3/128 strokes', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Save design', exact: true }).click()
  await expect(page.getByText('Workspace revision 2 saved.', { exact: false })).toBeVisible()
  const saved = await (await request.get(`${endpoint}/workspace`, { headers })).json()
  expect(saved.data.scenarios.option_a.items).toEqual([])
  expect(saved.data.scenarios.option_a.ground_paint.map((stroke) => stroke.texture)).toEqual(['lawn', 'deep', 'erase'])
  expect(saved.data.scenarios.option_b.ground_paint).toEqual([])
  const stale = await request.post(`${endpoint}/spatial-edit`, { headers, data: { workspace: initial, scenario: 'option_a', operation: 'clear_paint' } })
  expect(stale.status()).toBe(409)
  await panel.getByRole('button', { name: 'Clear ground paint', exact: true }).click()
  await expect.poll(async () => (await pixels()).painted).toBe(0)
  await town.getByRole('button', { name: 'Undo layout change', exact: true }).click()
  await expect.poll(async () => (await pixels()).painted).toBeGreaterThan(0)
  await page.getByRole('button', { name: 'Save design', exact: true }).click()
  await expect(page.getByText('Workspace revision 3 saved.', { exact: false })).toBeVisible()
  await mkdir('artifacts', { recursive: true })
  await page.screenshot({ path: 'artifacts/ground-paint-desktop.png' })
  await page.reload()
  await openDetailedWorkspace(page)
  await page.getByRole('button', { name: 'Map view', exact: true }).click()
  await openStudioTool(page, 'Layout')
  await town.getByRole('button', { name: 'Ground', exact: true }).click()
  await expect(panel.getByText('3/128 strokes', { exact: true })).toBeVisible()
  await expect.poll(async () => (await pixels()).painted).toBeGreaterThan(0)
  expect((await pixels()).outside).toBe(0)
  await page.setViewportSize({ width: 390, height: 844 })
  await panel.getByRole('heading', { name: 'Paint the ground' }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: 'artifacts/ground-paint-phone.png' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  expect((await request.put(`${endpoint}/access`, { headers, data: { user_id: identity.user.id, capabilities: ['read_project'] } })).ok()).toBeTruthy()
  expect((await request.post(`${endpoint}/spatial-edit`, { headers, data: { workspace: initial, scenario: 'option_a', operation: 'clear_paint' } })).status()).toBe(403)
})
