import { test, expect } from '@playwright/test'
import { mkdir } from 'node:fs/promises'
import { openDetailedWorkspace, openStudioTool } from '../studio-helpers.mjs'

test('town Layout estimates selected area, draws textured roads and stamps saved plants', async ({ page, request }) => {
  test.setTimeout(90000)
  page.setDefaultTimeout(15000)
  const errors = []
  page.on('pageerror', (error) => errors.push(error.message))
  const login = await request.post('http://127.0.0.1:8001/auth/v1/token', { data: { email: 'fixture@example.invalid', password: 'fixture-only' } })
  const headers = { Authorization: `Bearer ${(await login.json()).access_token}` }
  const org = (await (await request.get('/api/v1/session', { headers })).json()).organisations[0].id
  const project = await (await request.post(`/api/v1/organisations/${org}/projects`, { headers, data: { name: 'Town layout playground', purpose: 'contractor_proposal', stakeholder: 'Synthetic UI test', site: { bounds: [101.681, 3.131, 101.683, 3.133] } } })).json()
  const endpoint = `/api/v1/organisations/${org}/projects/${project.id}`
  const initial = await (await request.get(`${endpoint}/workspace`, { headers })).json()
  expect(initial.site_area_m2).toBeGreaterThan(40000)
  expect(initial.data).toBeNull()
  await page.goto('/')
  await page.getByLabel('Email address').fill('fixture@example.invalid')
  await page.getByLabel('Password', { exact: true }).fill('fixture-only')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  const organisation = page.getByLabel('Active organisation', { exact: true })
  await expect(organisation).toBeVisible()
  if (await organisation.inputValue() !== org) await organisation.selectOption(org)
  await page.getByRole('button', { name: /Town layout playground/ }).click()
  await openDetailedWorkspace(page)
  await page.getByRole('button', { name: 'Map view', exact: true }).click()
  await openStudioTool(page, 'Layout')
  await expect(page.getByText('SELECTED SITE · ESTIMATED')).toBeVisible()
  await page.getByRole('button', { name: 'Start building on this site', exact: true }).click()
  const town = page.getByRole('region', { name: 'Town builder layout', exact: true })
  await expect(town.getByText('YOUR SITE · ESTIMATED')).toBeVisible()
  await expect(page.getByText('Spatial editing tools', { exact: true })).toBeHidden()
  await town.getByRole('button', { name: 'Dirt', exact: true }).click()
  await town.getByRole('button', { name: 'Curved', exact: true }).click()
  const canvas = page.getByRole('region', { name: 'Geometry drawing canvas', exact: true }).locator('.mapboxgl-canvas')
  const box = await canvas.boundingBox()
  await page.mouse.move(box.x + box.width * 0.40, box.y + box.height * 0.48)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width * 0.51, box.y + box.height * 0.53, { steps: 7 })
  await page.mouse.up()
  await expect(town.getByText(/Validated preview:/)).toBeVisible()
  await mkdir('artifacts', { recursive: true })
  await page.screenshot({ path: 'artifacts/town-layout-road.png' })
  await town.getByRole('button', { name: 'Confirm road footprint', exact: true }).click()
  await town.getByRole('button', { name: 'Planting', exact: true }).click()
  await expect(town.getByRole('button', { name: /^Tree Simple canopy/ })).toHaveCount(0)
  for (const [kind, names] of [['Shrub', ['Leafy shrub', 'Low hedge', 'Ornamental grass']], ['Flowers', ['Daisies', 'Tulips', 'Lavender']]]) {
    await town.getByRole('button', { name: new RegExp(`^${kind} `) }).click()
    for (const [index, name] of names.entries()) {
      await town.getByRole('button', { name: new RegExp(`^${name} `) }).click()
      const response = page.waitForResponse((r) => r.url().endsWith('/spatial-edit') && r.request().method() === 'POST')
      await canvas.click({ position: { x: box.width * (0.36 + index * 0.025), y: box.height * (kind === 'Shrub' ? 0.55 : 0.58) } })
      expect((await response).ok()).toBeTruthy()
    }
  }
  await expect.poll(() => canvas.getAttribute('data-planted-plant-models')).toBe('6')
  await page.screenshot({ path: 'artifacts/town-layout-textures-plants.png' })
  await town.getByRole('button', { name: 'Select', exact: true }).click()
  await expect(town.getByText('Shrub 1', { exact: true })).toBeVisible()
  await expect(town.getByText('Flowers 1', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Save design', exact: true }).click()
  await expect(page.getByText('Workspace revision 1 saved.', { exact: false })).toBeVisible()
  const saved = await (await request.get(`${endpoint}/workspace`, { headers })).json()
  expect(saved.data.boundary_area_m2).toBeCloseTo(initial.site_area_m2, 1)
  expect(saved.data.scenarios.option_a.items.find((item) => item.road).road.surface).toBe('dirt')
  expect(saved.data.scenarios.option_a.items.filter((item) => item.layout_plant).map((item) => item.plant_variant)).toEqual(['leafy', 'hedge', 'grass', 'daisy', 'tulip', 'lavender'])
  expect(saved.data.scenarios.option_a.items.filter((item) => item.layout_plant).every((item) => item.quantity.value === 1 && item.rate_id === null)).toBeTruthy()
  expect(saved.data.scenarios.option_b.items).toEqual([])
  await town.getByRole('button', { name: 'Remove Flowers 1', exact: true }).click()
  await expect(town.getByText('Flowers 1', { exact: true })).toHaveCount(0)
  await town.getByRole('button', { name: 'Undo layout change', exact: true }).click()
  await expect(town.getByText('Flowers 1', { exact: true })).toBeVisible()
  await town.getByRole('button', { name: /^Shrub 2/ }).click()
  await page.getByRole('button', { name: 'Collapse working panel', exact: true }).click()
  await canvas.focus()
  for (let index = 0; index < 4; index++) await page.keyboard.press('+', { delay: 350 })
  await page.screenshot({ path: 'artifacts/plant-models-six.png' })
  await openStudioTool(page, 'Layout')
  await town.getByRole('button', { name: /^Flowers 2/ }).click()
  await page.getByRole('button', { name: 'Collapse working panel', exact: true }).click()
  await expect(canvas).toHaveAttribute('data-planted-plant-models', '6')
  await page.screenshot({ path: 'artifacts/plant-models-flowers.png', animations: 'disabled' })
  await openStudioTool(page, 'Layout')
  await page.reload()
  await openDetailedWorkspace(page)
  await expect.poll(() => page.getByRole('region', { name: 'Geometry drawing canvas', exact: true }).locator('.mapboxgl-canvas').getAttribute('data-planted-plant-models')).toBe('6')
  await page.getByRole('button', { name: 'Map view', exact: true }).click()
  await openStudioTool(page, 'Layout')
  await town.getByRole('button', { name: 'Planting', exact: true }).click()
  await town.getByRole('button', { name: /^Flowers Flower cluster/ }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await town.getByText('YOUR SITE · ESTIMATED').scrollIntoViewIfNeeded()
  await page.screenshot({ path: 'artifacts/town-layout-phone.png' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  expect(errors).toEqual([])
})
