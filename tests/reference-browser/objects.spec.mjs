import { openDetailedWorkspace } from '../studio-helpers.mjs'
import {test,expect} from '@playwright/test'
import {mkdir,writeFile} from 'node:fs/promises'
import {randomUUID} from 'node:crypto'

test('L07 palette placement, grouping, visibility, lock, persistence and real WebGL',async({page,request})=>{
  test.setTimeout(120000)
  const login=await request.post('http://127.0.0.1:8001/auth/v1/token',{data:{email:'fixture@example.invalid',password:'fixture-only'}})
  expect(login.ok()).toBeTruthy()
  const headers={Authorization:`Bearer ${(await login.json()).access_token}`}
  const org=(await (await request.get('/api/v1/session',{headers})).json()).organisations[0].id
  const result=await request.post(`/api/v1/organisations/${org}/projects`,{headers,data:{name:'L07 synthetic palette',purpose:'contractor_proposal',stakeholder:'Test only',site:{bounds:[101.681,3.131,101.683,3.133]}}})
  expect(result.status()).toBe(201)
  const project=await result.json(),endpoint=`/api/v1/organisations/${org}/projects/${project.id}`
  const polygon={type:'Polygon',coordinates:[[[101.681,3.131],[101.683,3.131],[101.683,3.133],[101.681,3.133],[101.681,3.131]]]}
  const target={id:randomUUID(),name:'Traced target',geometry:polygon,provenance:'estimated',source_note:'Synthetic control plan'}
  const data={expected_revision:0,boundary:polygon,boundary_provenance:'estimated',boundary_source:'Synthetic',targets:[target],scenarios:{baseline:{name:'Baseline',items:[]},option_a:{name:'A',items:[]},option_b:{name:'B',items:[]}}}
  expect((await request.post(`${endpoint}/workspace`,{headers,data})).ok()).toBeTruthy()
  await page.goto('/')
  await page.getByLabel('Email address').fill('fixture@example.invalid')
  await page.getByLabel('Password',{exact:true}).fill('fixture-only')
  await page.getByRole('button',{name:'Sign in',exact:true}).click()
  const organisation=page.getByRole('combobox',{name:'Active organisation',exact:true})
  await expect(organisation).toBeVisible()
  if(await organisation.inputValue()!==org) await organisation.selectOption(org)
  await page.getByRole('button',{name:/L07 synthetic palette/}).click()
  await openDetailedWorkspace(page)
  await page.getByRole('region',{name:'Ground geometry workspace',exact:true}).getByRole('button',{name:'A',exact:true}).click()
  const panel=page.getByRole('group',{name:'Licensed object palette',exact:true})
  await panel.getByRole('button',{name:'Precision object controls',exact:true}).click()
  await expect(panel.getByRole('img',{name:/thumbnail/})).toHaveCount(16)
  await panel.getByLabel('Search object presets',{exact:true}).fill('solar')
  await expect(panel.getByRole('img',{name:/thumbnail/})).toHaveCount(1)
  await panel.getByLabel('Search object presets',{exact:true}).fill('')
  await panel.getByLabel('Object group',{exact:true}).fill('Courtyard')
  await panel.getByRole('button',{name:'Place object',exact:true}).click()
  await expect(panel.getByRole('button',{name:'Duplicate object',exact:true})).toBeEnabled()
  await panel.getByRole('button',{name:'Duplicate object',exact:true}).click()
  await expect(panel.getByRole('button',{name:/Park bench copy .*visible/})).toBeVisible()
  await panel.getByLabel('Group east movement (m)',{exact:true}).fill('3')
  await panel.getByRole('button',{name:'Move group',exact:true}).click()
  await expect(panel.getByRole('button',{name:'Move group',exact:true})).toBeEnabled()
  await panel.getByLabel('Show object category Benches').uncheck()
  await panel.getByLabel('Show object category Benches').check()
  await panel.getByRole('button',{name:'Lock object',exact:true}).click()
  await expect(panel.getByRole('button',{name:'Apply object changes',exact:true})).toBeDisabled()
  await panel.getByRole('button',{name:'Unlock object',exact:true}).click()
  await expect(panel.getByRole('button',{name:'Apply object changes',exact:true})).toBeEnabled()
  await panel.getByRole('button',{name:'Hide object',exact:true}).click()
  await expect(panel.getByRole('button',{name:'Show object',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Validate & save workspace',exact:true}).click()
  await expect(page.getByText('Workspace revision 2 saved.',{exact:false})).toBeVisible()
  const saved=(await (await request.get(`${endpoint}/workspace`,{headers})).json()).data
  expect(saved.scenarios.option_a.items).toHaveLength(2)
  expect(saved.scenarios.option_a.items.every(i=>i.quantity.value===1&&i.object_instance.group==='Courtyard')).toBe(true)
  expect(saved.scenarios.option_a.items.filter(i=>i.visible)).toHaveLength(1)
  await page.reload();await openDetailedWorkspace(page)
  await page.getByRole('region',{name:'Ground geometry workspace',exact:true}).getByRole('button',{name:'A',exact:true}).click()
  await panel.getByRole('button',{name:'Precision object controls',exact:true}).click()
  await panel.getByLabel('Show 3D object preview and layout').check()
  const canvas=page.getByRole('region',{name:'Studio canvas'}).getByRole('img',{name:'Interactive 3D object scene'})
  await expect(canvas).toBeVisible({timeout:20000})
  await expect(page.getByText(/1 preset objects/)).toHaveCount(2)
  await mkdir('artifacts',{recursive:true})
  await canvas.screenshot({path:'artifacts/l07-layout.png'})
  await panel.getByRole('img',{name:'Interactive 3D object scene'}).first().screenshot({path:'artifacts/l07-bench.png'})
  await page.setViewportSize({width:390,height:844})
  expect((await canvas.boundingBox()).width).toBeLessThanOrEqual(390)
  await canvas.screenshot({path:'artifacts/l07-mobile.png'})
  await canvas.evaluate(c=>c.getContext('webgl2').getExtension('WEBGL_lose_context').loseContext())
  await expect(page.getByRole('region',{name:'Studio canvas'}).getByText(/3D context lost/)).toBeVisible()
  await expect(panel.getByLabel('Object longitude',{exact:true})).toBeVisible()
  const assets=['bench','bin','light','toilet','pergola','solar','play','bike','planter','path','fence','tree']
  data.expected_revision=2
  data.scenarios.option_a.items=Array.from({length:150},(_,i)=>({id:randomUUID(),name:`Load object ${i}`,kind:'object',geometry:null,provenance:'estimated',source_note:'Synthetic capacity fixture',object_instance:{asset_id:assets[i%12],longitude:101.6813+(i%15)*0.00009,latitude:3.1313+Math.floor(i/15)*0.0001}}))
  const started=Date.now()
  expect((await request.post(`${endpoint}/workspace`,{headers,data})).ok()).toBeTruthy()
  await page.setViewportSize({width:1280,height:900})
  await page.reload();await openDetailedWorkspace(page)
  await page.getByRole('region',{name:'Ground geometry workspace',exact:true}).getByRole('button',{name:'A',exact:true}).click()
  await panel.getByRole('button',{name:'Precision object controls',exact:true}).click()
  await panel.getByLabel('Show 3D object preview and layout').check()
  await expect(page.getByRole('region',{name:'Studio canvas'}).getByText(/150 preset objects/)).toBeVisible({timeout:20000})
  const scene=page.getByRole('region',{name:'Studio canvas'}).getByTestId('object-scene')
  const calls=Number(await scene.getAttribute('data-draw-calls')),triangles=Number(await scene.getAttribute('data-triangles'))
  expect(calls).toBeGreaterThan(0);expect(calls).toBeLessThan(100)
  expect(triangles).toBeGreaterThan(8000);expect(triangles).toBeLessThanOrEqual(38400)
  await page.getByRole('region',{name:'Studio canvas'}).screenshot({path:'artifacts/l07-capacity.png'})
  await writeFile('artifacts/l07-performance.json',JSON.stringify({instances:150,presets:12,draw_calls:calls,triangles,save_reload_render_ms:Date.now()-started,environment:'Local automated Chromium WebGL; not physical-device acceptance'},null,2))
})
