import { test, expect } from '@playwright/test'
import { mkdir } from 'node:fs/promises'
import { openDetailedWorkspace, openStudioTool } from '../studio-helpers.mjs'

test('four planted tree models resize, rotate, move, save and use sourced count-based estimates', async ({ page, request }) => {
  test.setTimeout(150000)
  page.setDefaultTimeout(15000)
  const errors = []
  page.on('pageerror', (error) => errors.push(error.message))
  const identity = await (await request.post('http://127.0.0.1:8001/auth/v1/token', { data: { email: 'fixture@example.invalid', password: 'fixture-only' } })).json()
  const headers = { Authorization: `Bearer ${identity.access_token}` }
  const org = (await (await request.get('/api/v1/session', { headers })).json()).organisations[0].id
  const project = await (await request.post(`/api/v1/organisations/${org}/projects`, { headers, data: { name: 'Planted tree playground', purpose: 'contractor_proposal', stakeholder: 'Synthetic test only', site: { bounds: [101.681, 3.131, 101.683, 3.133] } } })).json()
  const endpoint = `/api/v1/organisations/${org}/projects/${project.id}`
  const boundary = { type: 'Polygon', coordinates: [[[101.681,3.131],[101.683,3.131],[101.683,3.133],[101.681,3.133],[101.681,3.131]]] }
  const initial = { expected_revision: 0, boundary, boundary_source: 'Synthetic site extent', boundary_provenance: 'estimated', targets: [], scenarios: { baseline: { name: 'Baseline', items: [] }, option_a: { name: 'A', items: [] }, option_b: { name: 'B', items: [] } } }
  expect((await request.post(`${endpoint}/workspace`, { headers, data: initial })).ok()).toBeTruthy()
  const rate = await (await request.post(`/api/v1/organisations/${org}/rates`, { headers, data: { code: 'TREE-TEST', description: 'Synthetic installed stock per tree', unit: 'item', basis: 'cost', amount: '50', effective_date: '2026-11-13', valid_until: '2027-11-13', source_note: 'Synthetic fixture, not a supplier quote' } })).json()
  const wrongRate = await (await request.post(`/api/v1/organisations/${org}/rates`, { headers, data: { code: 'WRONG-AREA', description: 'Synthetic wrong unit', unit: 'm2', basis: 'cost', amount: '2', effective_date: '2026-11-13', source_note: 'Synthetic invalid tree rate' } })).json()
  await page.goto('/')
  await page.getByLabel('Email address').fill('fixture@example.invalid')
  await page.getByLabel('Password', { exact: true }).fill('fixture-only')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  const organisation = page.getByLabel('Active organisation', { exact: true })
  await expect(organisation).toBeVisible()
  if (await organisation.inputValue() !== org) await organisation.selectOption(org)
  await page.getByRole('button', { name: /Planted tree playground/ }).click()
  await openDetailedWorkspace(page)
  await page.getByRole('button', { name: 'Map view', exact: true }).click()
  await openStudioTool(page, 'Trees')
  const panel = page.getByRole('region', { name: 'Plant trees', exact: true })
  await expect(panel.locator('.tree-model-tray > button')).toHaveCount(4)
  await expect(page.getByRole('region', { name: 'Site tree inventory', exact: true })).toBeHidden()
  const canvas = page.getByRole('region', { name: 'Geometry drawing canvas', exact: true }).locator('.mapboxgl-canvas')
  const box = await canvas.boundingBox()
  for (let index = 0; index < 4; index++) {
    await panel.locator('.tree-model-tray > button').nth(index).click()
    const response = page.waitForResponse((value) => value.url().endsWith('/spatial-edit') && value.request().method() === 'POST')
    await canvas.click({ position: { x: box.width * (0.40 + index * 0.045), y: box.height * 0.53 } })
    expect((await response).ok()).toBeTruthy()
    await expect(panel.locator('.tree-planted-list > button')).toHaveCount(index + 1)
  }
  await panel.getByRole('button', { name: 'Select trees', exact: true }).click()
  await expect.poll(() => canvas.getAttribute('data-planted-tree-models')).toBe('4')
  const styles = await canvas.getAttribute('data-planted-tree-styles')
  for (const variant of ['canopy','columnar','evergreen','palm']) expect(styles).toContain(variant)
  await expect.poll(() => canvas.getAttribute('data-planted-tree-shadows')).toBe('4')
  await page.getByRole('button', { name: 'Sun context', exact: true }).click()
  await page.getByLabel('Shadow time', { exact: true }).fill('00:00')
  await expect.poll(() => canvas.getAttribute('data-planted-tree-shadows')).toBe('0')
  await expect(panel.getByText('Tree shadows hidden: night or very low sun.', { exact: true })).toBeVisible()
  await page.getByLabel('Shadow time', { exact: true }).fill('15:00')
  await expect.poll(() => canvas.getAttribute('data-planted-tree-shadows')).toBe('4')
  await page.getByRole('button', { name: 'Sun context', exact: true }).click()
  await page.getByRole('button', { name: 'Save design', exact: true }).click()
  await expect(page.getByText('Workspace revision 2 saved.', { exact: false })).toBeVisible()
  const incomplete = await (await request.post(`${endpoint}/estimates`, { headers, data: { expected_revision: 2, request_key: crypto.randomUUID(), scenario: 'option_a', method: 'markup', percent: '0', wastage_percent: '0', charges: [] } })).json()
  expect(incomplete.payload.complete).toBe(false)
  const names = ['Canopy tree 1', 'Columnar tree 2', 'Evergreen 3', 'Palm 4']
  for (let index = 0; index < names.length; index++) {
    await panel.locator('.tree-planted-list > button').nth(index).click()
    if (index === 0) {
      await panel.getByRole('button', { name: 'Large', exact: true }).click()
      await panel.getByRole('button', { name: 'Turn 45°', exact: true }).click()
    }
    await panel.getByLabel('Purchased stock specification', { exact: true }).fill(`Explicit synthetic ${names[index]} stock; installation included; not market data`)
    await panel.getByRole('combobox', { name: 'Per-tree rate', exact: true }).selectOption(rate.id)
    await panel.getByRole('checkbox', { name: 'I checked that this rate matches the purchased stock and inclusions.', exact: true }).check()
    await panel.getByRole('button', { name: 'Apply tree changes', exact: true }).click()
    await expect(panel.getByRole('button', { name: 'Apply tree changes', exact: true })).toBeDisabled()
  }
  await page.getByRole('button', { name: 'Save design', exact: true }).click()
  await expect(page.getByText('Workspace revision 3 saved.', { exact: false })).toBeVisible()
  let saved = await (await request.get(`${endpoint}/workspace`, { headers })).json()
  const first = saved.data.scenarios.option_a.items[0]
  expect(first.tree_design.scale).toBe(1.5)
  expect(first.tree_design.rotation_deg).toBe(45)
  expect(first.quantity.value).toBe(1)
  expect(saved.data.scenarios.option_b.items).toEqual([])
  await panel.locator('.tree-planted-list > button').first().click()
  await expect(panel.locator('.tree-planted-list > button').first()).toContainText('MYR 50.00')
  const marker = page.getByLabel('Drag selected tree to move it', { exact: true })
  const move = page.waitForResponse((value) => value.url().endsWith('/spatial-edit') && value.request().method() === 'POST')
  await marker.dragTo(canvas, { targetPosition: { x: box.width * 0.48, y: box.height * 0.51 } })
  expect((await move).ok()).toBeTruthy()
  await page.getByRole('button', { name: 'Save design', exact: true }).click()
  await expect(page.getByText('Workspace revision 4 saved.', { exact: false })).toBeVisible()
  saved = await (await request.get(`${endpoint}/workspace`, { headers })).json()
  expect(saved.data.scenarios.option_a.items[0].geometry).not.toEqual(first.geometry)
  expect(saved.data.scenarios.option_a.items[0].quantity.value).toBe(1)
  const clean = { ...first }; delete clean.quantity; delete clean.schedule
  const invalid = await request.post(`${endpoint}/spatial-edit`, { headers, data: { workspace: { ...initial, expected_revision: 4 }, scenario: 'option_a', operation: 'tree', tree_item: { ...clean, rate_id: wrongRate.id } } })
  expect(invalid.status()).toBe(422)
  const stale = await request.post(`${endpoint}/spatial-edit`, { headers, data: { workspace: initial, scenario: 'option_a', operation: 'tree', tree_item: clean } })
  expect(stale.status()).toBe(409)
  await mkdir('artifacts', { recursive: true })
  await panel.getByRole('button', { name: 'View in 3D', exact: true }).click()
  await panel.locator('.tree-planted-list > button').nth(1).click()
  const drawing = page.getByRole('region', { name: 'Geometry drawing canvas', exact: true })
  await drawing.getByRole('button', { name: 'Zoom out', exact: true }).click({ clickCount: 2 })
  await expect(canvas).toHaveAttribute('data-planted-tree-models', '4')
  await expect.poll(() => canvas.getAttribute('data-planted-tree-shadows')).toBe('4')
  await page.screenshot({ path: 'artifacts/proposed-trees-desktop.png' })
  await page.getByRole('button', { name: 'Collapse working panel', exact: true }).click()
  await page.screenshot({ path: 'artifacts/proposed-trees-models.png' })
  await openStudioTool(page, 'Trees')
  await panel.getByRole('button', { name: 'Review option estimate / manage rates', exact: true }).click()
  await page.getByLabel('Markup (%)', { exact: true }).fill('10')
  await page.getByLabel('Explicit area/length wastage (%)', { exact: true }).fill('0')
  const estimate = page.waitForResponse((value) => value.url().endsWith('/estimates') && value.request().method() === 'POST')
  await page.getByRole('button', { name: 'Calculate selected option estimate', exact: true }).click()
  const priced = await (await estimate).json()
  expect(priced.payload.complete).toBe(true)
  expect(priced.payload.lines).toHaveLength(4)
  expect(priced.payload.lines.every((line) => line.cost_total === '50.00')).toBeTruthy()
  expect(priced.payload.selling_total).toBe('220.00')
  await page.reload()
  await openDetailedWorkspace(page)
  await page.getByRole('button', { name: 'Map view', exact: true }).click()
  await openStudioTool(page, 'Trees')
  await expect(panel.locator('.tree-planted-list > button')).toHaveCount(4)
  await page.setViewportSize({ width: 390, height: 844 })
  await panel.locator('.tree-model-tray').scrollIntoViewIfNeeded()
  await page.screenshot({ path: 'artifacts/proposed-trees-phone.png' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  expect(errors).toEqual([])
  expect((await request.put(`${endpoint}/access`, { headers, data: { user_id: identity.user.id, capabilities: ['read_project'] } })).ok()).toBeTruthy()
  expect((await request.post(`${endpoint}/spatial-edit`, { headers, data: { workspace: { ...initial, expected_revision: 4 }, scenario: 'option_a', operation: 'tree', tree_item: clean } })).status()).toBe(403)
})
