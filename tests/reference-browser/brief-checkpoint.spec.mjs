import { test, expect } from '@playwright/test'
import { openProjectRecords } from '../studio-helpers.mjs'
import { readFile, mkdir } from 'node:fs/promises'

test('K01 FIXTURE STORAGE evidence acknowledgement becomes historical after brief edit', async ({ page, request }) => {
  const login = await request.post('http://127.0.0.1:8001/auth/v1/token', { data: { email: 'fixture@example.invalid', password: 'fixture-only' } })
  const headers = { Authorization: `Bearer ${(await login.json()).access_token}` }
  const org = (await (await request.get('/api/v1/session', { headers })).json()).organisations[0].id
  const project = await (await request.post(`/api/v1/organisations/${org}/projects`, { headers, data: { name: 'K01 Brief checkpoint', purpose: 'contractor_proposal', stakeholder: 'Fixture client', site: { bounds: [101.681,3.131,101.683,3.133] } } })).json()
  const base = `/api/v1/organisations/${org}/projects/${project.id}`
  const uploaded = await request.post(`${base}/evidence`, { headers, multipart: { description: 'Fixture client acknowledgement', source_note: 'Synthetic file; not customer acceptance', rights_confirmed: 'true', photo: { name: 'fixture.png', mimeType: 'image/png', buffer: await readFile('tests/fixtures/l05-green.png') } } })
  expect(uploaded.ok()).toBeTruthy()
  await page.goto('/')
  await page.getByLabel('Email address').fill('fixture@example.invalid')
  await page.getByLabel('Password', { exact: true }).fill('fixture-only')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await page.getByRole('button', { name: /K01 Brief checkpoint/ }).click()
  await page.getByRole('button', { name: 'Edit brief', exact: true }).click()
  await page.getByText('Agreed scope, assumptions and sources', { exact: true }).click()
  await page.getByLabel('Scope deliverables').fill('Concept layout and proposal')
  await page.getByLabel('Scope inclusions').fill('Paving and seating')
  await page.getByLabel('Scope exclusions').fill('Survey and construction')
  await page.getByLabel('Scope intended use').fill('Client decision')
  await page.getByLabel('Scope unresolved questions').fill('Verify underground services')
  await page.getByRole('button', { name: 'Add sourced brief fact' }).click()
  await page.getByLabel('Fact 1 statement').fill('Underground services are not located')
  await page.getByLabel('Fact 1 supplier / source').fill('Client briefing')
  await page.getByRole('button', { name: 'Save brief', exact: true }).click()
  await openProjectRecords(page)
  const panel = page.getByRole('region', { name: 'Agreed brief checkpoint' })
  await panel.getByText('Record a brief checkpoint', { exact: true }).click()
  await panel.getByLabel('Checkpoint note / outstanding work').fill('Awaiting documented acknowledgement')
  await panel.getByRole('button', { name: 'Record checkpoint', exact: true }).click()
  await expect(panel.getByText('Unconfirmed output policy: Draft previews only; issuing is blocked.')).toBeVisible()
  await panel.getByLabel('Brief acknowledgement status', { exact: true }).selectOption('acknowledged')
  await panel.getByLabel('External confirming person').fill('Fixture client representative')
  await panel.getByLabel('Confirmation date', { exact: true }).fill('2026-01-01')
  await panel.getByLabel('Confirmation method').fill('Email referring to this brief revision')
  await panel.getByLabel('Fixture client acknowledgement', { exact: true }).check()
  await panel.getByLabel('Checkpoint note / outstanding work').fill('Fixture acknowledges scope; services remain unresolved')
  await panel.getByRole('button', { name: 'Record checkpoint', exact: true }).click()
  await expect(panel.getByText('Acknowledgement recorded', { exact: true })).toBeVisible()
  await page.reload()
  await openProjectRecords(page)
  await expect(panel.getByText('Acknowledgement recorded', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Edit brief', exact: true }).click()
  await page.getByLabel('What problem should this project address?').fill('Scope changed after acknowledgement')
  await page.getByRole('button', { name: 'Save brief', exact: true }).click()
  await openProjectRecords(page)
  await expect(panel.locator('strong').filter({ hasText: /^Not confirmed$/ })).toBeVisible()
  await expect(panel.getByText(/The brief changed after the previous checkpoint/)).toBeVisible()
  await panel.getByText('Brief checkpoint history', { exact: true }).click()
  await expect(panel.getByText('Checkpoint 2 · brief revision 2 · acknowledged', { exact: true })).toBeVisible()
  await panel.getByText('Current scope and unresolved questions', { exact: true }).click()
  await expect(panel.getByText('Verify underground services', { exact: true }).first()).toBeVisible()
  await mkdir('artifacts', { recursive: true })
  await panel.screenshot({ path: 'artifacts/k01-brief-checkpoint.png' })
})
