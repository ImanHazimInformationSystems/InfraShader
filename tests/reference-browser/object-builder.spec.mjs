import { test, expect } from '@playwright/test'
import { mkdir } from 'node:fs/promises'
import { openDetailedWorkspace, openStudioTool } from '../studio-helpers.mjs'

test('landscape objects place, transform, draw fences, cast shadows and illuminate at night', async ({ page, request }) => {
  test.setTimeout(150000)
  page.setDefaultTimeout(15000)
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  const login=await (await request.post('http://127.0.0.1:8001/auth/v1/token',{data:{email:'fixture@example.invalid',password:'fixture-only'}})).json()
  const headers={Authorization:`Bearer ${login.access_token}`}
  const org=(await (await request.get('/api/v1/session',{headers})).json()).organisations[0].id
  const project=await (await request.post(`/api/v1/organisations/${org}/projects`,{headers,data:{name:'Landscape object playground',purpose:'contractor_proposal',stakeholder:'Synthetic fixture',site:{bounds:[101.681,3.131,101.683,3.133]}}})).json()
  const endpoint=`/api/v1/organisations/${org}/projects/${project.id}`
  const boundary={type:'Polygon',coordinates:[[[101.681,3.131],[101.683,3.131],[101.683,3.133],[101.681,3.133],[101.681,3.131]]]}
  const initial={expected_revision:0,boundary,boundary_source:'Synthetic',boundary_provenance:'estimated',targets:[],scenarios:{baseline:{name:'Baseline',items:[]},option_a:{name:'A',items:[]},option_b:{name:'B',items:[]}}}
  expect((await request.post(`${endpoint}/workspace`,{headers,data:initial})).ok()).toBeTruthy()
  await page.goto('/')
  await page.getByLabel('Email address').fill('fixture@example.invalid')
  await page.getByLabel('Password',{exact:true}).fill('fixture-only')
  await page.getByRole('button',{name:'Sign in',exact:true}).click()
  const organisation=page.getByLabel('Active organisation',{exact:true});await expect(organisation).toBeVisible()
  if(await organisation.inputValue()!==org)await organisation.selectOption(org)
  await page.getByRole('button',{name:/Landscape object playground/}).click()
  await openDetailedWorkspace(page)
  await page.getByLabel('Embed design on map', { exact:true }).check()
  await page.getByRole('button', { name: 'Map view', exact: true }).click()
  const tools=page.getByRole('navigation',{name:'Studio tools'})
  await openStudioTool(page, 'Objects')
  const panel=page.getByRole('region',{name:'Landscape object builder',exact:true})
  const canvas=page.getByRole('region',{name:'Geometry drawing canvas',exact:true}).locator('.mapboxgl-canvas')
  const box=await canvas.boundingBox()
  async function place(name,x,y) {
    await panel.getByRole('button',{name,exact:true}).click()
    const response=page.waitForResponse(r=>r.url().endsWith('/object-preview')&&r.request().method()==='POST')
    await canvas.click({position:{x:box.width*x,y:box.height*y}})
    expect((await response).ok()).toBeTruthy()
    await expect(panel.getByRole('button',{name:'Select / stop placing',exact:true})).toBeEnabled()
  }
  await place('Park bench',.42,.48)
  await panel.getByRole('button',{name:'Select / stop placing',exact:true}).click()
  await panel.getByLabel('Overall size',{exact:true}).press('End')
  for (let index=0; index<20; index++) await panel.getByLabel('Tilt forward / back',{exact:true}).press('ArrowRight')
  const changed=page.waitForResponse(r=>r.url().endsWith('/object-preview')&&r.request().method()==='POST')
  await panel.getByRole('button',{name:'Apply object changes',exact:true}).click();expect((await changed).ok()).toBeTruthy()
  await expect(panel.getByRole('button',{name:'Apply object changes',exact:true})).toBeDisabled()
  const moved=page.waitForResponse(r=>r.url().endsWith('/object-preview')&&r.request().method()==='POST')
  await page.getByLabel('Drag selected object to move it',{exact:true}).dragTo(canvas,{targetPosition:{x:box.width*.40,y:box.height*.48}})
  expect((await moved).ok()).toBeTruthy()
  await place('Garden gazebo',.48,.50)
  await panel.getByRole('button',{name:'Timber fence segment',exact:true}).click()
  const fence=page.waitForResponse(r=>r.url().endsWith('/spatial-edit')&&r.request().method()==='POST')
  await page.mouse.move(box.x+box.width*.34,box.y+box.height*.57);await page.mouse.down()
  await page.mouse.move(box.x+box.width*.43,box.y+box.height*.57,{steps:8});await page.mouse.up()
  expect((await fence).ok()).toBeTruthy()
  await panel.getByRole('button',{name:'Select / stop placing',exact:true}).click()
  await panel.getByRole('button',{name:'Lighting',exact:true}).click()
  await place('Lamp post',.40,.50);await place('Small path lamp',.44,.52);await place('Ground lamp',.48,.54)
  await panel.getByRole('button',{name:'Select / stop placing',exact:true}).click()
  await expect.poll(async()=>Number(await canvas.getAttribute('data-object-shadows'))).toBeGreaterThan(0)
  await page.getByRole('button',{name:'Sun context',exact:true}).click()
  await page.getByLabel('Shadow time',{exact:true}).fill('00:00')
  await expect.poll(()=>canvas.getAttribute('data-object-lights')).toBe('3')
  await expect(canvas).toHaveAttribute('data-object-shadows','0')
  await panel.getByLabel('Enable this light',{exact:true}).uncheck()
  await panel.getByRole('button',{name:'Apply object changes',exact:true}).click()
  await expect.poll(()=>canvas.getAttribute('data-object-lights')).toBe('2')
  await page.getByRole('button',{name:'Sun context',exact:true}).click()
  await page.getByRole('button',{name: 'Save design', exact: true}).click()
  await expect(page.getByText('Workspace revision 2 saved.',{exact:false})).toBeVisible()
  const saved=await (await request.get(`${endpoint}/workspace`,{headers})).json()
  const items=saved.data.scenarios.option_a.items
  expect(items.find(i=>i.object_instance.asset_id==='bench').object_instance.tilt_deg).toBe(20)
  expect(items.find(i=>i.object_instance.asset_id==='bench').quantity.value).toBe(1)
  expect(items.filter(i=>i.object_instance.asset_id==='fence').length).toBeGreaterThan(1)
  expect(saved.data.scenarios.option_b.items).toEqual([])
  expect(items.every(i=>i.rate_id===null)).toBeTruthy()
  await mkdir('artifacts',{recursive:true})
  await panel.locator('.object-builder-list > button').filter({hasText:'Park bench'}).click()
  await expect.poll(()=>canvas.getAttribute('data-object-lights')).toBe('2')
  await panel.locator('.object-category-tabs').scrollIntoViewIfNeeded()
  await page.screenshot({path:'artifacts/object-builder-night.png'})
  await page.getByRole('button',{name:'Collapse working panel',exact:true}).click()
  await page.screenshot({path:'artifacts/object-builder-night-scene.png'})
  await openStudioTool(page, 'Objects')
  await page.getByRole('button',{name:'Sun context',exact:true}).click()
  await page.getByLabel('Shadow time',{exact:true}).fill('09:00')
  await expect.poll(()=>canvas.getAttribute('data-object-lights')).toBe('0')
  await page.getByRole('button',{name:'Sun context',exact:true}).click()
  await page.screenshot({path:'artifacts/object-builder-day.png'})
  await page.reload();await openDetailedWorkspace(page)
  await page.getByLabel('Embed design on map', { exact:true }).check()
  await expect.poll(async()=>Number(await page.getByRole('region',{name:'Geometry drawing canvas',exact:true}).locator('.mapboxgl-canvas').getAttribute('data-object-shadows'))).toBeGreaterThan(0)
  await page.getByRole('button', { name: 'Map view', exact: true }).click()
  await openStudioTool(page, 'Objects')
  await page.setViewportSize({width:390,height:844})
  await panel.locator('.object-builder-tray').scrollIntoViewIfNeeded()
  await page.screenshot({path:'artifacts/object-builder-phone.png'})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy()
  expect(errors).toEqual([])
  expect((await request.post(`${endpoint}/spatial-edit`,{headers,data:{workspace:initial,scenario:'option_a',operation:'fence',fence_points:[[101.682,3.132],[101.6821,3.132]]}})).status()).toBe(409)
})
