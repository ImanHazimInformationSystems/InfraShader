import { test, expect } from '@playwright/test'
import { randomUUID } from 'node:crypto'
import { mkdir } from 'node:fs/promises'
import { openDetailedWorkspace, openStudioTool } from '../studio-helpers.mjs'

test('L31 drag, curve/area edits, cancel, revisioned layers and preliminary estimate', async ({ page, request }) => {
  test.setTimeout(180000)
  page.setDefaultTimeout(15000)
  const login = await request.post('http://127.0.0.1:8001/auth/v1/token', { data: { email: 'fixture@example.invalid', password: 'fixture-only' } })
  const identity = await login.json()
  const headers = { Authorization: `Bearer ${identity.access_token}` }
  const org = (await (await request.get('/api/v1/session', { headers })).json()).organisations[0].id
  const response = await request.post(`/api/v1/organisations/${org}/projects`, { headers, data: { name: 'Road drawing workflow', purpose: 'contractor_proposal', stakeholder: 'Synthetic test only', site: { bounds: [101.681, 3.131, 101.683, 3.133] } } })
  expect(response.status()).toBe(201)
  const project = await response.json()
  const endpoint = `/api/v1/organisations/${org}/projects/${project.id}`
  const boundary = { type: 'Polygon', coordinates: [[[101.681, 3.131], [101.683, 3.131], [101.683, 3.133], [101.681, 3.133], [101.681, 3.131]]] }
  const initial = { expected_revision: 0, boundary, boundary_source: 'Synthetic site bounds', boundary_provenance: 'estimated', targets: [], scenarios: { baseline: { name: 'Baseline', items: [] }, option_a: { name: 'A', items: [] }, option_b: { name: 'B', items: [] } } }
  expect((await request.post(`${endpoint}/workspace`, { headers, data: initial })).ok()).toBeTruthy()
  const rate = await (await request.post(`/api/v1/organisations/${org}/rates`, { headers, data: { code: 'ROAD-TEST', description: 'Synthetic layer rate', unit: 'm3', basis: 'cost', amount: '10', effective_date: '2026-10-01', valid_until: '2027-12-31', source_note: 'Synthetic test fixture, not a market price' } })).json()
  await page.goto('/')
  await page.getByLabel('Email address').fill('fixture@example.invalid')
  await page.getByLabel('Password', { exact: true }).fill('fixture-only')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  const activeOrg = page.getByLabel('Active organisation', { exact: true })
  await expect(activeOrg).toBeVisible()
  if (await activeOrg.inputValue() !== org) await activeOrg.selectOption(org)
  await page.getByRole('button', { name: /Road drawing workflow/ }).click()
  await openDetailedWorkspace(page)
  await page.getByRole('button', { name: 'A', exact: true }).first().click()
  const roads = page.getByRole('region', { name: 'Roads and driveways', exact: true })
  await roads.getByRole('button', { name: 'Draw a road', exact: true }).click()
  await roads.getByLabel('Road width (m)', { exact: true }).fill('4')
  await roads.getByText('Measurement notes', { exact: true }).click()
  await roads.getByRole('textbox', { name: 'Road measurement source / assumptions', exact: true }).fill('Synthetic concept trace; constant width, flat site assumption; not surveyed')
  const canvas = page.getByRole('region', { name: 'Geometry drawing canvas', exact: true }).locator('.mapboxgl-canvas')
  await canvas.scrollIntoViewIfNeeded()
  const box = await canvas.boundingBox()
  await page.mouse.move(box.x + box.width * 0.43, box.y + box.height * 0.5)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width * 0.57, box.y + box.height * 0.5, { steps: 9 })
  await page.mouse.up()
  await expect(roads.getByText(/Validated preview:/)).toBeVisible()
  expect((await (await request.get(`${endpoint}/workspace`, { headers })).json()).revision).toBe(1)
  await roads.getByRole('button', { name: 'Confirm road footprint', exact: true }).click()
  await expect(roads.getByRole('button', { name: 'Edit road shape' })).toHaveCount(1)
  await page.getByRole('button', { name: 'Undo workspace edit', exact: true }).click()
  await roads.getByRole('button', { name: 'Draw a road', exact: true }).click()
  await roads.getByRole('button', { name: 'Cancel road', exact: true }).click()
  await expect(roads.getByRole('button', { name: 'Edit road shape' })).toHaveCount(0)
  await roads.getByRole('button', { name: 'Draw a road', exact: true }).click()
  await roads.getByLabel('Road name', { exact: true }).fill('Proposed driveway')
  await roads.getByRole('button', { name: 'Curved', exact: true }).click()
  await roads.getByLabel('Road width (m)', { exact: true }).fill('4')
  await roads.getByText('Measurement notes', { exact: true }).click()
  await roads.getByRole('textbox', { name: 'Road measurement source / assumptions', exact: true }).fill('Synthetic control points; constant width, no grade/drainage design')
  await roads.getByText('Precise points & coordinates', { exact: true }).click()
  for (const [i, point] of [[101.6816, 3.1318], [101.682, 3.1321], [101.6824, 3.1318]].entries()) {
    await roads.getByRole('button', { name: 'Add control point', exact: true }).click()
    await roads.getByLabel(`Road point ${i + 1} longitude`, { exact: true }).fill(String(point[0]))
    await roads.getByLabel(`Road point ${i + 1} latitude`, { exact: true }).fill(String(point[1]))
  }
  await expect(roads.getByText(/Validated preview:/)).toBeVisible()
  await mkdir('artifacts', { recursive: true })
  await roads.screenshot({ path: 'artifacts/l31-road-desktop.png' })
  await roads.getByRole('button', { name: 'Confirm road footprint', exact: true }).click()
  await expect(roads.getByText('Layers missing — unpriced')).toBeVisible()
  await page.getByRole('button', { name: 'Validate & save workspace', exact: true }).click()
  await expect(page.getByText('Workspace revision 2 saved.', { exact: false })).toBeVisible()
  const estimate = (revision) => request.post(`${endpoint}/estimates`, { headers, data: { expected_revision: revision, request_key: randomUUID(), scenario: 'option_a', method: 'markup', percent: '0', wastage_percent: '0', charges: [] } })
  const incomplete = await (await estimate(2)).json()
  expect(incomplete.payload.complete).toBe(false)
  let saved = await (await request.get(`${endpoint}/workspace`, { headers })).json()
  const road = saved.data.scenarios.option_a.items[0]
  expect(road.road.mode).toBe('curve')
  const curveArea = road.quantity.value
  const stale = await request.post(`${endpoint}/spatial-edit`, { headers, data: { workspace: { ...initial, expected_revision: 1 }, scenario: 'option_a', operation: 'road', road_item: { id: randomUUID(), kind: 'area', name: 'Stale road', source_note: 'Synthetic', provenance: 'estimated', road: road.road } } })
  expect(stale.status()).toBe(409)
  await roads.getByRole('button', { name: 'Edit road shape', exact: true }).click()
  await roads.getByLabel('Road width (m)', { exact: true }).fill('6')
  await expect(roads.getByText(/Validated preview:/)).toBeVisible()
  await roads.getByRole('button', { name: 'Confirm road footprint', exact: true }).click()
  await roads.getByRole('button', { name: 'Road layers and cost', exact: true }).click()
  const panel = page.getByRole('group', { name: 'Planting and materials', exact: true })
  await expect(panel.getByRole('combobox', { name: 'Record type', exact: true })).toHaveValue('material')
  await expect(panel.getByRole('combobox', { name: 'Assembly use', exact: true })).toHaveValue('road')
  for (const [label, value] of Object.entries({ 'Assembly code': 'ROAD01', 'Assembly material': 'Synthetic base', 'Assembly finish': 'Fixture finish', 'Assembly source': 'User reviewed synthetic recipe', 'Component 1 thickness_mm': '100' })) await panel.getByLabel(label, { exact: true }).fill(value)
  await panel.getByLabel('I reviewed and approve this quantity recipe').check()
  await panel.getByRole('button', { name: 'Validate and apply source record', exact: true }).click()
  await expect(panel.getByRole('cell', { name: 'Unpriced', exact: true })).toBeVisible()
  await panel.getByRole('combobox', { name: 'Component 1 rate', exact: true }).selectOption(rate.id)
  await panel.getByLabel('I reviewed and approve this quantity recipe').check()
  await panel.getByRole('button', { name: 'Validate and apply source record', exact: true }).click()
  await page.getByRole('button', { name: 'Validate & save workspace', exact: true }).click()
  await expect(page.getByText('Workspace revision 3 saved.', { exact: false })).toBeVisible()
  saved = await (await request.get(`${endpoint}/workspace`, { headers })).json()
  expect(saved.data.scenarios.option_a.items[0].quantity.value).toBeGreaterThan(curveArea)
  expect(saved.data.scenarios.option_a.items[0].schedule[0].unit).toBe('m3')
  expect(saved.data.scenarios.option_b.items).toEqual([])
  await roads.getByRole('button', { name: 'Review preliminary estimate', exact: true }).click()
  const responsePromise = page.waitForResponse((response) => response.url().endsWith('/estimates') && response.request().method() === 'POST')
  await page.getByRole('button', { name: 'Calculate selected option estimate', exact: true }).click()
  const priced = await (await responsePromise).json()
  expect(priced.payload.complete).toBe(true)
  expect(Number(priced.payload.lines[0].cost_total)).toBeGreaterThan(0)
  await mkdir('artifacts', { recursive: true })
  await page.screenshot({ path: 'artifacts/l31-road-estimate.png', fullPage: true })
  await roads.getByRole('button', { name: 'Edit road shape', exact: true }).click()
  await roads.getByRole('button', { name: 'Free shape', exact: true }).click()
  await expect(roads.getByText(/Validated preview:/)).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: 'Map view', exact: true }).click()
  await openStudioTool(page, 'Layout')
  await roads.getByRole('heading', { name: 'Build a road or path', exact: true }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: 'artifacts/l31-road-phone.png' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await roads.getByRole('button', { name: 'Confirm road footprint', exact: true }).click()
  await page.getByRole('button', { name: 'Save design', exact: true }).click()
  await expect(page.getByText('Workspace revision 4 saved.', { exact: false })).toBeVisible()
  await page.reload()
  await openDetailedWorkspace(page)
  await page.getByRole('button', { name: 'A', exact: true }).first().click()
  await expect(roads.getByText(/1 layer\(s\)/)).toBeVisible()
  expect((await (await request.get(`${endpoint}/workspace`, { headers })).json()).data.scenarios.option_a.items[0].road.mode).toBe('area')
  expect((await (await request.get(`${endpoint}/artifacts`, { headers })).json()).items.some((artifact) => artifact.id === priced.id)).toBeTruthy()
  expect((await request.put(`${endpoint}/access`, { headers, data: { user_id: identity.user.id, capabilities: ['read_project'] } })).ok()).toBeTruthy()
  const denied = await request.post(`${endpoint}/spatial-edit`, { headers, data: { workspace: initial, scenario: 'option_a', operation: 'road', road_item: { id: randomUUID(), name: 'Denied road', kind: 'area', source_note: 'Synthetic', provenance: 'estimated', road: road.road } } })
  expect(denied.status()).toBe(403)
})
