import { test, expect } from '@playwright/test'
import { openStudioTool } from '../studio-helpers.mjs'
import { mkdir } from 'node:fs/promises'

test('site shape controls retain rotated polygon through project and workspace persistence', async ({ page, request }) => {
 test.setTimeout(90000)
 const login=await request.post('http://127.0.0.1:8001/auth/v1/token',{data:{email:'fixture@example.invalid',password:'fixture-only'}})
 const headers={Authorization:`Bearer ${(await login.json()).access_token}`}
 const org=(await (await request.get('/api/v1/session',{headers})).json()).organisations[0].id
 await page.goto('/')
 await page.getByLabel('Email address').fill('fixture@example.invalid')
 await page.getByLabel('Password',{exact:true}).fill('fixture-only')
 await page.getByRole('button',{name:'Sign in',exact:true}).click()
 await page.getByRole('combobox',{name:'Active organisation',exact:true}).selectOption(org)
 await page.getByRole('button',{name:'Open Design Studio',exact:true}).click()
 await page.getByRole('button',{name:'New project',exact:true}).click()
 const names=['West longitude','South latitude','East longitude','North latitude']
 const original=await Promise.all(names.map(name=>page.getByLabel(name,{exact:true}).inputValue()))
 const select=page.getByRole('button',{name:'Select site on map',exact:true})
 await expect(select).toBeEnabled({timeout:30000})
 await select.click()
 const panel=page.getByRole('region',{name:'Site selection controls'})
 await expect(panel).toBeVisible()
 await panel.getByRole('button',{name:'Ellipse',exact:true}).click()
 await expect(panel.getByRole('status')).toContainText('48 outline vertices')
 await panel.getByLabel('Rotate by (degrees)').fill('30')
 await panel.getByRole('button',{name:'Rotate',exact:true}).click()
 const move=page.getByRole('button',{name:'Move site',exact:true})
 const drag=await move.boundingBox()
 await page.mouse.move(drag.x+15,drag.y+15);await page.mouse.down();await page.mouse.move(drag.x+45,drag.y+25,{steps:6});await page.mouse.up()
 await move.focus();await page.keyboard.press('ArrowRight');await expect(move).toBeFocused()
 await panel.getByRole('button',{name:'Undo',exact:true}).click()
 await panel.getByRole('button',{name:'Redo',exact:true}).click()
 await panel.getByRole('button',{name:'Cancel',exact:true}).click()
 expect(await Promise.all(names.map(name=>page.getByLabel(name,{exact:true}).inputValue()))).toEqual(original)
 await select.click()
 await panel.getByRole('button',{name:'Custom polygon',exact:true}).click()
 const canvas=page.getByRole('region',{name:'Explore site map'}).locator('canvas').first()
 const box=await canvas.boundingBox()
 for(const [x,y] of [[.3,.28],[.52,.28],[.5,.5],[.34,.56]])await page.mouse.click(box.x+box.width*x,box.y+box.height*y)
 await expect(panel.getByRole('status')).toContainText('4 outline vertices')
 await panel.getByRole('button',{name:'Finish polygon',exact:true}).click()
 await panel.getByLabel('Rotate by (degrees)').fill('25')
 await panel.getByRole('button',{name:'Rotate',exact:true}).click()
 await panel.getByLabel('Resize to (%)').fill('80')
 await panel.getByRole('button',{name:'Resize',exact:true}).click()
 await mkdir('artifacts',{recursive:true})
 await page.screenshot({path:'artifacts/site-selection-desktop.png',animations:'disabled'})
 await page.setViewportSize({width:390,height:844})
 await page.screenshot({path:'artifacts/site-selection-phone.png',animations:'disabled'})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy()
 await panel.getByRole('button',{name:'Apply site shape',exact:true}).click()
 await page.getByRole('button',{name:'Continue with this site',exact:true}).click()
 await page.getByLabel('Project name').fill('Rotated shape handoff')
 await page.getByLabel('Client / customer').fill('Fixture')
 await page.getByRole('button',{name:'Create project',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Rotated shape handoff',exact:true})).toBeVisible()
 const saved=(await (await request.get(`/api/v1/organisations/${org}/projects?query=Rotated%20shape%20handoff`,{headers})).json()).items[0]
 expect(saved.site.outline.coordinates[0]).toHaveLength(5)
 const ring=saved.site.outline.coordinates[0]
 expect(ring[0][0]).not.toEqual(ring[1][0]);expect(ring[0][1]).not.toEqual(ring[1][1])
 await page.reload()
 await expect(page.getByRole('heading',{name:'Rotated shape handoff',exact:true})).toBeVisible()
 const workspace=`/api/v1/organisations/${org}/projects/${saved.id}/workspace`
 expect((await (await request.get(workspace,{headers})).json()).data).toBeNull()
 await page.getByRole('button',{name:'Open design map',exact:true}).click()
 await openStudioTool(page, 'Layout')
 await page.getByRole('button',{name:'Start building on this site'}).click()
 await page.getByRole('button',{name: 'Save design', exact: true}).click()
 await expect.poll(async()=>(await (await request.get(workspace,{headers})).json()).revision).toBe(1)
 expect((await (await request.get(workspace,{headers})).json()).data.boundary).toEqual(saved.site.outline)
 const invalid=await request.post(`/api/v1/organisations/${org}/projects`,{headers,data:{name:'Bad envelope',purpose:'contractor_proposal',stakeholder:'Fixture',site:{...saved.site,bounds:[0,0,.01,.01]}}})
 expect(invalid.status()).toBe(422)
})
