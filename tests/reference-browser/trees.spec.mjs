import { test, expect } from '@playwright/test'
import { openStudioTool } from '../studio-helpers.mjs'
import { mkdir } from 'node:fs/promises'

test('tree inventory transfers, renders, saves decisions and retains a conflicting draft', async ({ page, request }) => {
  test.setTimeout(120000)
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  const login = await request.post('http://127.0.0.1:8001/auth/v1/token', { data: { email: 'fixture@example.invalid', password: 'fixture-only' } })
  const headers = { Authorization: `Bearer ${(await login.json()).access_token}` }
  const org = (await (await request.get('/api/v1/session', { headers })).json()).organisations[0].id
  await page.goto('/')
  await page.getByLabel('Email address').fill('fixture@example.invalid')
  await page.getByLabel('Password', { exact: true }).fill('fixture-only')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await page.getByRole('combobox', { name: 'Active organisation', exact: true }).selectOption(org)
  await page.getByRole('button', { name: 'Open Design Studio', exact: true }).click()
  await page.getByRole('button', { name: 'New project', exact: true }).click()
  const coordinates = await Promise.all(['West longitude', 'South latitude', 'East longitude', 'North latitude'].map(name => page.getByLabel(name, { exact: true }).inputValue()))
  const [w, s, e, n] = coordinates.map(Number), longitude = (w + e) / 2, latitude = (s + n) / 2
  await page.getByRole('button', { name: 'Review site trees', exact: true }).click()
  const inventory = page.getByRole('region', { name: 'Site tree inventory', exact: true })
  await page.route('https://overpass-api.de/api/interpreter?*', route => {
    expect(route.request().headers().authorization).toBeUndefined()
    return route.fulfill({ json: { elements: [{ type: 'node', id: 1, lon: longitude, lat: latitude, tags: { natural: 'tree' } }] } })
  })
  await inventory.getByRole('button', { name: 'Load mapped trees in this site', exact: true }).click()
  await expect(inventory.getByRole('status').filter({ hasText: '1 mapped trees returned' })).toBeVisible()
  await inventory.getByLabel('Tree dataset source', { exact: true }).fill('Browser fixture inventory')
  await inventory.getByLabel('Tree dataset licence / permission', { exact: true }).fill('Synthetic test data only')
  const feature = (id, lon, properties) => ({ type: 'Feature', id, properties, geometry: { type: 'Point', coordinates: [lon, latitude] } })
  await inventory.getByLabel('Tree inventory GeoJSON', { exact: true }).setInputFiles({ name: 'trees.geojson', mimeType: 'application/geo+json', buffer: Buffer.from(JSON.stringify({ type: 'FeatureCollection', features: [feature('one', longitude, { name: 'Known crown', height_m: 12, crown_diameter_m: 8 }), feature('two', longitude + (e - w) / 8, { name: 'Unknown crown' }), feature('outside', e + 1, { name: 'Outside tree' })] })) })
  await expect(inventory.getByText('2 context trees inside this site; 1 outside.', { exact: false })).toBeVisible()
  await inventory.getByRole('button', { name: 'Include trees inside site in draft', exact: true }).click()
  await expect(inventory.getByLabel('Decision for Known crown', { exact: true })).toHaveValue('retain')
  await inventory.getByRole('button', { name: 'Mark all site trees for removal', exact: true }).click()
  await expect(inventory.getByLabel('Decision for Unknown crown', { exact: true })).toHaveValue('remove')
  await inventory.getByRole('button', { name: 'Undo tree change', exact: true }).click()
  await expect(inventory.getByLabel('Decision for Unknown crown', { exact: true })).toHaveValue('retain')
  await inventory.getByRole('button', { name: 'Apply tree decisions', exact: true }).click()
  await expect(inventory.getByRole('button', { name: 'Apply tree decisions', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Close tree panel', exact: true }).click()
  await expect.poll(() => page.locator('canvas[data-tree-models]').first().getAttribute('data-tree-models')).toBe('1')
  await page.getByRole('button', { name: 'Continue with this site', exact: true }).click()
  await page.getByLabel('Project name').fill('Tree inventory overhaul fixture')
  await page.getByLabel('Client / customer').fill('Fixture')
  await page.getByRole('button', { name: 'Create project', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Tree inventory overhaul fixture', exact: true })).toBeVisible()
  const saved = (await (await request.get(`/api/v1/organisations/${org}/projects?query=Tree%20inventory%20overhaul%20fixture`, { headers })).json()).items[0]
  expect(saved.site.trees).toHaveLength(2)
  expect(saved.site.trees[1].height_m).toBeNull()
  const endpoint = `/api/v1/organisations/${org}/projects/${saved.id}`
  await page.getByRole('button', { name: 'Open design map', exact: true }).click()
  await openStudioTool(page, 'Trees')
  await page.getByRole('button', { name: 'Existing site', exact: true }).click()
  await inventory.getByLabel('Decision for Known crown', { exact: true }).selectOption('remove')
  await inventory.getByRole('button', { name: 'Save project tree decisions', exact: true }).click()
  await expect(inventory.getByRole('button', { name: 'Save project tree decisions', exact: true })).toBeDisabled()
  const second = await (await request.get(endpoint, { headers })).json()
  expect(second.revision).toBe(saved.revision + 1)
  expect(second.site.trees[0]).toEqual({ ...saved.site.trees[0], status: 'remove' })
  await inventory.getByLabel('Decision for Known crown', { exact: true }).selectOption('retain')
  const concurrent = await request.patch(endpoint, { headers, data: { expected_revision: second.revision, name: second.name } })
  expect(concurrent.ok()).toBeTruthy()
  await inventory.getByRole('button', { name: 'Save project tree decisions', exact: true }).click()
  await expect(inventory.getByRole('alert')).toContainText('changed')
  await expect(inventory.getByLabel('Decision for Known crown', { exact: true })).toHaveValue('retain')
  await expect(inventory.getByRole('button', { name: 'Save project tree decisions', exact: true })).toBeEnabled()
  page.once('dialog', dialog => dialog.accept())
  await inventory.getByRole('button', { name: 'Reload saved trees', exact: true }).click()
  await expect(inventory.getByLabel('Decision for Known crown', { exact: true })).toHaveValue('remove')
  await inventory.getByRole('button', { name: 'Keep all site trees', exact: true }).click()
  await inventory.getByRole('button', { name: 'Save project tree decisions', exact: true }).click()
  await expect(inventory.getByRole('button', { name: 'Save project tree decisions', exact: true })).toBeDisabled()
  await expect.poll(() => page.locator('canvas[data-tree-models]').first().getAttribute('data-tree-models')).toBe('1')
  await mkdir('artifacts', { recursive: true })
  await inventory.getByRole('button', { name: 'Add tree record', exact: true }).click()
  await inventory.getByLabel('Tree name', { exact: true }).fill('Manual observation')
  await inventory.getByLabel('Tree longitude', { exact: true }).fill(String(longitude))
  await inventory.getByLabel('Tree latitude', { exact: true }).fill(String(latitude + (n-s)/8))
  await inventory.getByRole('button', { name: 'Apply tree record to draft', exact: true }).click()
  await inventory.getByRole('button', { name: 'Save project tree decisions', exact: true }).click()
  await expect(inventory.getByRole('button', { name: 'Save project tree decisions', exact: true })).toBeDisabled()
  const manual = (await (await request.get(endpoint, { headers })).json()).site.trees.find(t => t.name === 'Manual observation')
  expect(manual.origin).toBe('manual')
  expect(manual.height_m).toBeNull()
  await page.getByRole('complementary', { name: 'Studio working panel' }).evaluate(el => { el.scrollTop = 0 })
  await page.screenshot({ path: 'artifacts/tree-inventory-desktop.png', animations: 'disabled' })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: 'artifacts/tree-inventory-phone.png', animations: 'disabled' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.setViewportSize({ width: 1280, height: 900 })
  await inventory.getByText('Tree display & preview limits', { exact: true }).click()
  await inventory.getByLabel('Illustrative tree shadow preview', { exact: true }).check()
  const canvas = page.getByRole('region', { name: 'Geometry drawing canvas', exact: true }).locator('canvas[data-tree-models]')
  await canvas.evaluate(node => {
    const extension = node.getContext('webgl2').getExtension('WEBGL_lose_context')
    if (!extension) throw new Error('Context-loss extension unavailable')
    window.restoreTreeContext = () => extension.restoreContext()
    extension.loseContext()
  })
  await expect(inventory.getByRole('status').filter({ hasText: 'graphics were interrupted' })).toContainText('Tree decisions are retained')
  await page.evaluate(() => window.restoreTreeContext())
  await expect(canvas).toHaveAttribute('data-tree-models', '1')
  await page.getByRole('button', { name: 'Collapse working panel', exact: true }).click()
  await canvas.focus()
  for (let i = 0; i < 5; i++) await page.keyboard.press('+', { delay: 350 })
  // Camera animations settle through an observable scale change, then capture the actual model.
  await expect(page.getByRole('region', { name: 'Geometry drawing canvas', exact: true }).locator('.mapboxgl-ctrl-scale')).toContainText(/^(1|2|3|5|10|20|30|50)\s*m$/)
  await page.screenshot({ path: 'artifacts/tree-model-context.png', animations: 'disabled' })
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Tree inventory overhaul fixture', exact: true, level: 1 })).toBeVisible({ timeout: 15000 })
  expect(errors).toEqual([])
})
