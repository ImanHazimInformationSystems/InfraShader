import { test, expect } from '@playwright/test'
import { openProjectRecords } from '../studio-helpers.mjs'
import { mkdir } from 'node:fs/promises'

test('L01 contact reuse, opportunity work queue, templates and clean duplicate persist', async ({ page, request }) => {
  test.setTimeout(60000)
  const login = await request.post(`${process.env.INFRA_TEST_API_URL || 'http://127.0.0.1:8000'}/auth/v1/token`, { data: { email: 'fixture@example.invalid', password: 'fixture-only' } })
  const headers = { Authorization: `Bearer ${(await login.json()).access_token}` }
  const org = (await (await request.get('/api/v1/session', { headers })).json()).organisations[0].id
  const base = `/api/v1/organisations/${org}`
  const project = await (await request.post(`${base}/projects`, { headers, data: { name: 'L01 Courtyard', purpose: 'contractor_proposal', stakeholder: 'Hub sponsor', problem: 'Improve access', site: { bounds: [101.681, 3.131, 101.683, 3.133] } } })).json()
  const geometry = { type: 'Polygon', coordinates: [[[101.681,3.131],[101.682,3.131],[101.682,3.132],[101.681,3.132],[101.681,3.131]]] }
  const design = await request.post(`${base}/projects/${project.id}/workspace`, { headers, data: { expected_revision: 0, boundary: geometry, boundary_provenance: 'estimated', boundary_source: 'L01 fixture only', targets: [], scenarios: { baseline: { name: 'Baseline', items: [] }, option_a: { name: 'Option A', items: [{ id: '22222222-2222-4222-8222-222222222222', name: 'Paving', kind: 'area', geometry, source_note: 'Fixture only', provenance: 'estimated' }] }, option_b: { name: 'Option B', items: [] } } } })
  expect(design.ok()).toBeTruthy()
  await page.goto('/')
  await page.getByLabel('Email address').fill('fixture@example.invalid')
  await page.getByLabel('Password', { exact: true }).fill('fixture-only')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await page.getByRole('button', { name: /L01 Courtyard/ }).click()
  await page.getByRole('button', { name: 'Edit brief', exact: true }).click()
  await page.getByLabel('Opportunity owner', { exact: true }).fill('Hub planner')
  await page.getByLabel('Opportunity due date', { exact: true }).fill('2026-12-01')
  await page.getByLabel('Opportunity stage', { exact: true }).selectOption('qualified')
  await page.getByLabel('Opportunity source', { exact: true }).fill('Client referral')
  await page.getByLabel('Tags (comma separated, up to 20)').fill('urgent,courtyard')
  await page.getByText('Choose or maintain my client contacts', { exact: true }).click()
  await page.getByLabel('Contact name', { exact: true }).fill('L01 Customer')
  await page.getByLabel('Contact email', { exact: true }).fill('client@example.invalid')
  await page.getByLabel('Contact source', { exact: true }).fill('Customer supplied')
  await page.getByRole('button', { name: 'Save contact', exact: true }).click()
  await page.getByRole('button', { name: 'Use L01 Customer', exact: true }).click()
  await page.getByRole('button', { name: 'Edit L01 Customer', exact: true }).click()
  await page.getByLabel('Contact phone', { exact: true }).fill('012-0000000')
  await page.getByRole('button', { name: 'Save contact', exact: true }).click()
  await expect(page.getByText('012-0000000', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: 'History of L01 Customer', exact: true }).click()
  await expect(page.getByText('Revision 2', { exact: true })).toBeVisible()
  await page.getByText('Budget, priorities and stakeholders', { exact: true }).click()
  await page.getByLabel('Budget ceiling (MYR)', { exact: true }).fill('10000.50')
  await page.getByRole('button', { name: 'Save brief', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Edit brief', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByText(/qualified · Hub planner/)).toBeVisible()
  const fresh = await (await request.get(`${base}/projects/${project.id}`, { headers })).json()
  expect(fresh.details.opportunity.client.name).toBe('L01 Customer')
  expect(fresh.details.opportunity.client.phone).toBe('') // Library edit never rewrites a project snapshot.
  expect(fresh.details.budget).toBe('10000.50')
  await openProjectRecords(page)
  await page.getByText('Save or maintain a reusable brief template', { exact: true }).click()
  await page.getByLabel('Template name', { exact: true }).fill('L01 Access template')
  await page.getByRole('button', { name: 'Save template', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Edit L01 Access template', exact: true })).toBeVisible()
  await page.getByText('Duplicate this project', { exact: true }).click()
  await page.getByLabel('New project name', { exact: true }).fill('L01 New draft')
  await page.getByLabel('Include saved design at the same site').check()
  await expect(page.getByText(/Design revision 1/)).toBeVisible()
  await page.getByRole('button', { name: 'Create duplicate project', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1, name: 'L01 New draft', exact: true })).toBeVisible()
  await expect(page.getByText(/enquiry · Unassigned/)).toBeVisible()
  const copied = (await (await request.get(`${base}/projects?query=L01%20New%20draft`, { headers })).json()).items[0]
  expect(copied.revision).toBe(1)
  expect(copied.id).not.toBe(project.id)
  const copyDesign = await (await request.get(`${base}/projects/${copied.id}/workspace`, { headers })).json()
  expect(copyDesign.revision).toBe(1)
  expect(copyDesign.data.scenarios.option_a.items[0].quantity.value).toBeGreaterThan(0)
  // The duplicate opens in the immersive studio; leave it through Project details.
  await page.getByRole('button', { name: 'Project details', exact: true }).click()
  await page.getByRole('navigation').getByRole('button', { name: 'Projects', exact: true }).click()
  await page.getByText(/^More filters and options/).click()
  await page.getByLabel('Opportunity stage filter', { exact: true }).selectOption('qualified')
  await page.getByRole('button', { name: 'List view', exact: true }).click()
  await expect(page.getByRole('cell', { name: '2026-12-01', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'L01 New draft', exact: true })).toHaveCount(0)
  await mkdir('artifacts', { recursive: true })
  await page.screenshot({ path: 'artifacts/l01-project-hub.png', fullPage: true })
  // Create from a saved template using the existing selected-site creation route.
  await page.goto('/studio/create')
  await page.getByText('Start from my brief templates', { exact: true }).click()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'Use L01 Access template', exact: true }).click()
  await expect(page.getByLabel('What problem should this project address?')).toHaveValue('Improve access')
  await page.getByLabel('Project name', { exact: false }).fill('L01 Templated project')
  await page.getByLabel('Client / customer', { exact: false }).fill('New client')
  await page.getByRole('button', { name: 'Create project', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'L01 Templated project', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByText('Improve access', { exact: true }).first()).toBeVisible()
})
