"""Generate the product UI manifest and coverage view from canonical tracking CSVs.

This records interface coverage, never functional completion. No Excel output.
Run python scripts/ui-catalogue.py [--check].
"""
import argparse
import csv
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / "docs/tracking"


def load(name):
    with (BASE / name).open(encoding="utf-8-sig", newline="") as stream:
        return list(csv.DictReader(stream))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rows = [row for row in load("feature-register.csv") if row["Count in roadmap"] == "Yes"]
    coverage = load("ui-coverage.csv")
    by_id = {row["Feature ID"]: row for row in coverage}
    assert len(rows) == len(coverage) == len(by_id) == 85, "Expected 84 baseline features plus L31 addendum in UI coverage"
    assert set(by_id) == {row["Feature ID"] for row in rows}, "UI coverage ID mismatch"
    manifest = []
    lines = [
        "# Roadmap-to-UI coverage",
        "",
        "Generated by `python scripts/ui-catalogue.py` from the canonical feature register and `docs/tracking/ui-coverage.csv`.",
        "The UI map is canonical for interface placement only. Functional status, verification, deployment and acceptance remain in the existing registers.",
        "",
        "## Source and scope",
        "",
        "Approved catalogue baseline: `output/pdf/InfraShader_Full_Feature_Catalogue_2026-11-11.pdf` (all 23 pages read). The attached Desktop PDF is byte-identical; the separately requested suffix `(1)` file is absent. See [concept reconciliation](UI_CONCEPT_RECONCILIATION.md) for verified source hashes and description clarifications. The PDF's suggested placements are planning guidance, as stated on page 2.",
        "Exactly 85 project roadmap features are covered: the 84-feature PDF baseline plus user-requested L31. F/D/E aliases and K01-K06 refinements inform their parent workflows and do not create extra screens or feature totals.",
        "",
        "`UI-only/demo` means interactive ephemeral preview state, never API persistence. `UI-only + connected subset` means the new preview includes a context-aware link to an inspected existing workflow, not that the whole feature is implemented. `Connected subset` opens the existing project workflow without illustrative preview inputs; remaining feature scope and acceptance stay in the feature register. `Planned` means a staged preview with no domain service. Existing APIs, server grants, calculations and issuance remain authoritative.",
        "",
        "## Coverage",
        "",
        "| ID | Feature | Source priority | Workspace / UI location | UI state | Existing subset / remaining connection |",
        "|---|---|---|---|---|---|",
    ]
    for row in rows:
        ui = by_id[row["Feature ID"]]
        assert ui["UI state"] in {"UI-only/demo", "UI-only + connected subset", "Connected subset", "Planned"}
        assert ui["Template"] in {"register", "brief", "canvas", "comparison", "scorecard", "document", "dashboard", "assistant", "settings", "schedule"}
        item = dict(id=row["Feature ID"], name=row["Feature name"], priority=row["Priority"],
                    workspace=row["Workspace/audience"], scope=row["Requirement summary"],
                    implementation=row["Repository-audited implementation status"], group=ui["Group"],
                    state=ui["UI state"], template=ui["Template"], fields=ui["Preview fields"].split("; "),
                    tool=ui["Existing tool"], connection=ui["Connection note"],
                    related=row["Related IDs"], resources=row["Resource IDs"])
        manifest.append(item)
        route = ui["Route"]
        note = ui["Connection note"].replace("|", "/")
        lines.append(f'| {row["Feature ID"]} | {row["Feature name"]} | {row["Priority"]} | `{route}` / {ui["Surface"]} | {ui["UI state"]} | {note} |')
    pdf = ROOT / "output/pdf/InfraShader_Full_Feature_Catalogue_2026-11-11.pdf"
    lines += ["", "## Reproduction and maintenance", "",
              "Edit placement/state/preview metadata in `docs/tracking/ui-coverage.csv`; preserve the 84 PDF-baseline IDs plus L31. Run `python scripts/ui-catalogue.py`, then `python scripts/ui-catalogue.py --check`. Update domain acceptance records separately only when verified domain behaviour changes.",
              "UI implementation: `apps/web/src/product/` and the existing App/route integration. Common previews are keyed by feature ID and discarded when leaving the surface; applying a preview is never labelled Saved. Only the existing connected workflows save real project data. Capability-driven workspace availability is preserved.",
              "Research and design decisions: [UI design brief](UI_DESIGN.md). Actual verification and remaining gates: [UI evidence](tracking/evidence/product-ui-2026-11-11.md).",
              "", "Catalogue SHA-256: `" + hashlib.sha256(pdf.read_bytes()).hexdigest() + "`.", ""]
    outputs = {
        ROOT / "apps/web/src/product/catalogue.json": json.dumps(manifest, ensure_ascii=False, indent=2) + "\n",
        ROOT / "docs/UI_COVERAGE.md": "\n".join(lines),
    }
    for path, text in outputs.items():
        if args.check:
            assert path.exists() and path.read_text(encoding="utf-8") == text, f"Outdated generated UI view: {path}"
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    print("UI coverage validated: 85 project roadmap features (84 PDF baseline + L31 addendum); 38 baseline aliases and 6 refinements excluded from totals.")


if __name__ == "__main__":
    main()
